const { execFileSync, spawnSync } = require('node:child_process');
const { currentBranch, validBranch } = require('./scripts/check-branch-name.cjs');

function cleanMessage(raw) {
  const config = key => spawnSync('git', ['config', '--get', key], { encoding: 'utf8' }).stdout.trim();
  const comment = config('core.commentString') || config('core.commentChar') || '#';
  const lines = raw.replace(/\r\n/g, '\n').split('\n');
  const scissors = lines.indexOf(`${comment} ------------------------ >8 ------------------------`);
  const message = (scissors < 0 ? lines : lines.slice(0, scissors)).join('\n');
  return execFileSync('git', ['stripspace', '--strip-comments'], { input: message, encoding: 'utf8' });
}

function policy({ raw }) {
  const branch = currentBranch();
  if (!validBranch(branch)) return [false, 'Use a permitted branch (detached HEAD is unsupported).'];
  const lines = cleanMessage(raw).trimEnd().split('\n');
  const subject = lines[0];
  if (subject.length > 100 || !/^[a-z]+(?:\([a-zA-Z0-9_./-]+\))?!?: \S.* \((?:DEN-\d+|planning|owner)\)$/.test(subject)) {
    return [false, 'Use a Conventional Commit subject of at most 100 characters ending in (DEN-n), (planning), or (owner).'];
  }
  if (lines[1] !== '' || !lines[2]?.trim()) {
    return [false, 'Separate the subject and a non-empty explanatory body with a blank line.'];
  }
  const aiName = /(?:claude|codex|grok|anthropic|openai|xai|chatgpt|copilot|gemini|\bgpt\b|\bbot\b|\bAI\b)/i;
  const aiMarker = lines.some(line =>
    /^\W*generated\s+(?:by|with)\b/i.test(line) && aiName.test(line));
  const aiCoauthor = lines.some(line => {
    const author = line.match(/^\s*Co-Authored-By:\s*([^<]*)/i);
    return author && aiName.test(author[1]);
  });
  if (aiMarker || aiCoauthor) {
    return [false, 'Remove AI co-author lines and Generated by/with AI markers.'];
  }
  const mentions = lines.filter(line => /^\s*AI-Assisted-By\s*:/i.test(line));
  const trailers = lines.filter(line => /^AI-Assisted-By: (Claude|Codex|Grok)$/.test(line));
  const vendor = branch.split('/')[1];
  const agent = branch.startsWith('agent/');
  if (mentions.length > 1 || mentions.length !== trailers.length || (agent && trailers.length !== 1)) {
    return [false, 'Agent commits require exactly one AI-Assisted-By: Claude|Codex|Grok trailer; owner commits may omit it.'];
  }
  if (trailers.length) {
    const boundary = lines.lastIndexOf('');
    const trailerBlock = lines.slice(boundary + 1);
    if (boundary < 3 || !lines.slice(2, boundary).some(line => line.trim() && !/^(?:AI-Assisted-By|Signed-off-by|Co-authored-by):/i.test(line)) ||
        !trailerBlock.includes(trailers[0]) || !trailerBlock.every(line => /^[A-Za-z][A-Za-z-]*: \S.*$/.test(line))) {
      return [false, 'Put the trailer in a final trailer block separated from the explanatory body by a blank line.'];
    }
    const engines = { claude: 'Claude', codex: 'Codex', grok: 'Grok' };
    if (agent && engines[vendor] && trailers[0] !== `AI-Assisted-By: ${engines[vendor]}`) {
      return [false, `The ${vendor} branch requires AI-Assisted-By: ${engines[vendor]}.`];
    }
  }
  return [true, 'D-037 commit policy'];
}

module.exports = {
  defaultIgnores: false,
  plugins: [{ rules: { 'streamden-policy': policy } }],
  rules: { 'streamden-policy': [2, 'always'] },
};
