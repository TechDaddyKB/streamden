import { readFileSync } from "node:fs";

export const tokens = JSON.parse(readFileSync(new URL("../src/tokens.json", import.meta.url), "utf8"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** Declarations that do not change between themes. */
function shared() {
  const out = [];
  for (const [k, v] of Object.entries(tokens.font)) out.push([`font-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.text)) out.push([`text-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.space)) out.push([`space-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.radius)) out.push([`radius-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.color.ramp)) out.push([`ramp-${k}`, v]);
  out.push(["focus-width", tokens.focus.width], ["focus-offset", tokens.focus.offset]);
  return out;
}

function themed(name) {
  const out = [];
  for (const [k, v] of Object.entries(tokens.color.themes[name])) out.push([`color-${kebab(k)}`, v]);
  for (const [k, v] of Object.entries(tokens.shadow[name])) out.push([`shadow-${k}`, v]);
  out.push(["focus-ring", `${tokens.focus.width} solid var(--sd-color-focus)`]);
  return out;
}

const block = (selector, decls, indent = "", extra = "") =>
  `${indent}${selector} {\n${extra}${decls.map(([k, v]) => `${indent}  --sd-${k}: ${v};`).join("\n")}\n${indent}}\n`;

export function buildCss() {
  const reduced = ["fast", "base", "slow"].map((k) => [`motion-${k}`, "0ms"]);
  return [
    "/* Generated by web/kit/scripts/build-css.mjs from src/tokens.json. Do not edit. */\n",
    block(":root", Object.entries(tokens.motion).map(([k, v]) => [`motion-${k}`, v])),
    block(':root,\n[data-theme="dark"]', [...shared(), ...themed("dark")], "", "  color-scheme: dark;\n"),
    block('[data-theme="light"]', themed("light"), "", "  color-scheme: light;\n"),
    `@media (prefers-reduced-motion: reduce) {\n${block(":root", reduced, "  ")}}\n`,
  ].join("\n");
}
