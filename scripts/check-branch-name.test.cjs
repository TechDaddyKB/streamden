const assert = require('node:assert/strict');
const branches = require('./check-branch-name.cjs');
const configPath = require.resolve('../commitlint.config.cjs');
const originalBranch = branches.currentBranch;
let checks = 0;

function check(branch, message, expected) {
  branches.currentBranch = () => branch;
  delete require.cache[configPath];
  const config = require(configPath);
  const [valid, reason] = config.plugins[0].rules['streamden-policy']({ raw: message });
  assert.equal(valid, expected, `${branch}: ${JSON.stringify(message)}: ${reason}`);
  assert.equal(config.defaultIgnores, false);
  checks++;
}

const branch = 'agent/codex/DEN-12-repo-hygiene';
const message = 'chore(repo): add hooks (DEN-12)\n\nExplain the change and verification.\n\nAI-Assisted-By: Codex\n';
try {
  for (const name of ['main', 'owner/docs', branch, 'agent/other/DEN-1-tools']) {
    assert.equal(branches.validBranch(name), true);
    checks++;
  }
  for (const name of ['', 'feature/hooks', 'agent/codex/DEN-12-Bad', 'agent/unknown/DEN-1-tools', 'owner/']) {
    assert.equal(branches.validBranch(name), false);
    check(name, message, false);
  }
  check(branch, message, true);
  const subjectLength = message.split('\n')[0].length;
  check(branch, message.replace('add hooks', 'x'.repeat(9 + 100 - subjectLength)), true);
  check(branch, message.replace('add hooks', 'x'.repeat(9 + 101 - subjectLength)), false);
  check(branch, message.replaceAll('\n', '\r\n'), true);
  check(branch, message.replace('Explain the change and verification.', 'Checks: passed.'), true);
  for (const vendor of ['claude', 'grok']) {
    const engine = vendor === 'claude' ? 'Claude' : 'Grok';
    check(`agent/${vendor}/DEN-12-hooks`, message.replace('Codex', engine), true);
    check(`agent/${vendor}/DEN-12-hooks`, message, false);
  }
  check('agent/other/DEN-12-hooks', message, true);
  for (const suffix of ['planning', 'owner']) check(branch, message.replace('DEN-12)', `${suffix})`), true);
  for (const owner of ['main', 'owner/docs']) {
    check(owner, message, true);
    check(owner, message.replace('\nAI-Assisted-By: Codex\n', ''), true);
  }
  for (const invalid of [
    '', 'Merge branch main', 'Revert "change"', 'fixup! chore: hooks (DEN-12)',
    message.replace('chore(repo):', 'not conventional'),
    message.replace('(DEN-12)', '(DEN-x)'),
    message.replace('add hooks', 'x'.repeat(101)),
    message.replace(' (DEN-12)', ' (DEN-12) extra'),
    message.replace('\n\nExplain', '\nExplain'),
    message.replace('Explain the change and verification.\n\n', ''),
    message.replace('Explain the change and verification.', ''),
    message.replace('\nAI-Assisted-By: Codex\n', ''),
    message.replace('By: Codex', 'By: Claude'),
    message.replace('By: Codex', 'By: Other'),
    message.replace('AI-Assisted-By:', 'ai-assisted-by:'),
    message + 'AI-Assisted-By: Codex\n',
    message + '\nAI-Assisted-By: Codex\n',
    message + '\nExtra prose after the trailer.\n',
    message.replace('\n\nAI-', '\nAI-'),
    message.replace('Explain the change and verification.', 'Generated by Codex'),
    message.replace('Explain the change and verification.', 'Co-Authored-By: Claude <test@example.com>'),
    message.replace('Explain the change and verification.', 'Co-Authored-By: GPT-6 <test@example.com>'),
  ]) check(branch, invalid, false);
  check(branch, message + 'Signed-off-by: Human <human@example.com>\n', true);
  check(branch, message.replace('Explain the change and verification.', 'Co-Authored-By: Human <human@example.com>\nHuman contribution explained.'), true);
  console.log(`PASS: ${checks} branch and commit-policy checks`);
} finally {
  branches.currentBranch = originalBranch;
  delete require.cache[configPath];
}
