// Exercise real Git editor/rebase paths with private fixture hooks. Never install
// or modify hooks in the shared clone.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync, execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const temp = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'den12-hooks-'));
const env = { ...process.env, LEFTHOOK: '1', LEFTHOOK_VERBOSE: '0', FORCE_COLOR: '0',
  GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null' };
function run(command, args, expected = 0) {
  const result = spawnSync(command, args, { cwd: temp, env, encoding: 'utf8' });
  assert.equal(result.status, expected, `${command} ${args.join(' ')}\n${result.stdout}\n${result.stderr}`);
  checks++;
  return result.stdout.trim();
}
const git = (...args) => run('git', args);
try {
  git('init', '-b', branch);
  git('config', 'user.name', 'Hook Test');
  git('config', 'user.email', 'hook-test@example.invalid');
  const hooks = path.join(temp, '.git/hooks');
  git('config', 'core.hooksPath', hooks);
  const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'],
    { cwd: root, encoding: 'utf8' }).trim();
  if (!fs.existsSync(path.join(common, 'hooks/commit-msg')) ||
      !fs.existsSync(path.join(common, 'hooks/pre-commit'))) {
    // Also support a fresh clone where hooks have not been installed yet.
    fs.copyFileSync(path.join(root, 'lefthook.yml'), path.join(temp, 'lefthook.yml'));
    run(path.join(root, 'node_modules/.bin/lefthook'), ['install']);
    fs.unlinkSync(path.join(temp, 'lefthook.yml'));
  } else for (const hook of ['pre-commit', 'commit-msg']) {
    fs.copyFileSync(path.join(common, 'hooks', hook), path.join(hooks, hook));
    fs.chmodSync(path.join(hooks, hook), 0o755);
  }
  // The currently installed shared hooks must allow branches with no config.
  git('commit', '--allow-empty', '-m', 'fixture without lefthook config');
  for (const file of ['commitlint.config.cjs', 'lefthook.yml', '.editorconfig']) {
    fs.copyFileSync(path.join(root, file), path.join(temp, file));
  }
  fs.mkdirSync(path.join(temp, 'scripts'));
  fs.copyFileSync(path.join(root, 'scripts/check-branch-name.cjs'),
    path.join(temp, 'scripts/check-branch-name.cjs'));
  fs.copyFileSync(path.join(root, 'scripts/check-branch-name-commit.cjs'),
    path.join(temp, 'scripts/check-branch-name-commit.cjs'));
  const missing = spawnSync(process.execPath, ['scripts/check-branch-name-commit.cjs', 'message.txt'],
    { cwd: temp, env, encoding: 'utf8' });
  assert.equal(missing.status, 1);
  assert.equal(missing.stderr.trim(), 'Commit tooling missing: run pnpm install --frozen-lockfile --ignore-scripts in this worktree.');
  assert.equal(missing.stdout, '');
  checks += 3;
  fs.symlinkSync(path.join(root, 'node_modules'), path.join(temp, 'node_modules'), 'dir');
  const messagePath = path.join(temp, 'message.txt');
  fs.writeFileSync(messagePath, message);
  const editor = path.join(temp, 'editor.cjs');
  fs.writeFileSync(editor, `const fs = require('node:fs');
const file = process.argv[2];
fs.writeFileSync(file, process.env.DEN12_MESSAGE + (process.env.DEN12_REWORD ? '' : fs.readFileSync(file, 'utf8').replace(/^# seed\\n/, '')));
`);
  env.GIT_EDITOR = `"${process.execPath}" "${editor}"`;
  env.DEN12_MESSAGE = message;
  fs.writeFileSync(path.join(temp, 'fixture.txt'), 'editor commit\n');
  git('add', 'fixture.txt');
  git('commit', '-v');
  assert.equal(git('log', '-1', '--format=%B'), message.trim());
  git('config', 'core.commentChar', ';');
  fs.appendFileSync(path.join(temp, 'fixture.txt'), 'custom comments\n');
  git('add', 'fixture.txt');
  git('commit', '-v');
  git('config', '--unset', 'core.commentChar');
  // R1: -m and -F keep comment lines, including AI markers after trailers.
  const issueMessage = message.replace('Explain the change and verification.', '#42 is fixed by this change.');
  git('commit', '--allow-empty', '-m', issueMessage);
  assert.equal(git('log', '-1', '--format=%B'), issueMessage.trim());
  fs.writeFileSync(messagePath, issueMessage);
  git('commit', '--allow-empty', '-F', messagePath);
  assert.equal(git('log', '-1', '--format=%B'), issueMessage.trim());
  const markerMessage = message + '\n# 🤖 Generated with [Claude Code](https://claude.com/claude-code)\n';
  run('git', ['commit', '--allow-empty', '-m', markerMessage], 1);
  fs.writeFileSync(messagePath, markerMessage);
  run('git', ['commit', '--allow-empty', '-F', messagePath], 1);
  fs.writeFileSync(messagePath, message);
  // Explicit configured cleanup also applies without an editor.
  git('-c', 'commit.cleanup=strip', 'commit', '--allow-empty', '-m', markerMessage);
  assert.equal(git('log', '-1', '--format=%B'), message.trim());
  for (const mode of ['whitespace', 'verbatim', 'scissors']) {
    git('-c', `commit.cleanup=${mode}`, 'commit', '--allow-empty', '-m', issueMessage);
    run('git', ['-c', `commit.cleanup=${mode}`, 'commit', '--allow-empty', '-m', markerMessage], 1);
  }
  // R2: auto selects # normally and ; when the initial message uses #.
  git('config', 'core.commentChar', 'auto');
  git('commit', '--allow-empty', '-v');
  const template = path.join(temp, 'template.txt');
  fs.writeFileSync(template, '# seed\n');
  env.DEN12_MESSAGE = issueMessage;
  git('commit', '--allow-empty', '-v', '-t', template);
  assert.equal(git('log', '-1', '--format=%B'), issueMessage.trim());
  env.DEN12_MESSAGE = message;
  git('config', '--unset', 'core.commentChar');
  // R3: neutral names at AI domains fail on the actual hook path too.
  for (const domain of ['anthropic.com', 'openai.com', 'x.ai']) {
    run('git', ['commit', '--allow-empty', '-m', message + `Co-Authored-By: Assistant <noreply@${domain}>\n`], 1);
  }
  const sequenceEditor = path.join(temp, 'sequence.cjs');
  fs.writeFileSync(sequenceEditor, `const fs = require('node:fs');
const file = process.argv[2];
fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace(/^pick /m, 'reword '));
`);
  env.GIT_SEQUENCE_EDITOR = `"${process.execPath}" "${sequenceEditor}"`;
  env.DEN12_REWORD = '1';
  git('rebase', '-i', 'HEAD~1');
  assert.equal(git('branch', '--show-current'), branch);
  git('checkout', '--detach');
  run(process.execPath, ['scripts/check-branch-name.cjs'], 1);
  run(path.join(root, 'node_modules/.bin/lefthook'), ['run', 'commit-msg', '--', messagePath], 1);
  // Both backends store head-name in worktree-specific Git state.
  for (const backend of ['rebase-merge', 'rebase-apply']) {
    const state = path.join(temp, '.git', backend);
    fs.mkdirSync(state);
    fs.writeFileSync(path.join(state, 'head-name'), `refs/heads/${branch}\n`);
    assert.match(run(process.execPath, ['scripts/check-branch-name.cjs']), /Branch OK:/);
    run(path.join(root, 'node_modules/.bin/lefthook'), ['run', 'pre-commit', '--force']);
    run(path.join(root, 'node_modules/.bin/lefthook'), ['run', 'commit-msg', '--', messagePath]);
    fs.writeFileSync(path.join(state, 'head-name'), 'refs/heads/agent/claude/DEN-12-hooks\n');
    run(path.join(root, 'node_modules/.bin/lefthook'), ['run', 'commit-msg', '--', messagePath], 1);
    fs.rmSync(state, { recursive: true });
  }
  // Direct hook runs must never invoke pnpm/install or create workspace files.
  assert.equal(fs.existsSync(path.join(temp, 'pnpm-lock.yaml')), false);
  assert.equal(fs.existsSync(path.join(temp, 'pnpm-workspace.yaml')), false);
  checks += 2;
  const editorconfig = fs.readFileSync(path.join(temp, '.editorconfig'), 'utf8');
  function indentation(filename) {
    let active = false;
    const settings = {};
    for (const line of editorconfig.split('\n')) {
      const section = line.match(/^\[(.*)\]$/);
      if (section) active = section[1] === '*' || section[1] === filename ||
        (section[1] === '*.rs' && filename.endsWith('.rs'));
      else if (active && line.includes('=')) {
        const [key, value] = line.split('=').map(part => part.trim());
        settings[key] = value;
      }
    }
    return settings;
  }
  assert.equal(indentation('main.rs').indent_size, '4');
  assert.equal(indentation('Makefile').indent_style, 'tab');
  assert.equal(indentation('index.ts').indent_size, '2');
  checks += 3;
  console.log(`PASS: ${checks} checks (R1 cleanup, R2 auto comments, R3 AI domains, R4 missing dependencies; policy, editor/rebase, shared hooks, no lockfiles, indentation)`);
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
