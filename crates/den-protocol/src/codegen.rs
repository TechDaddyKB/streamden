fn collect_ts_files(
    root: &Path,
    dir: &Path,
    files: &mut GeneratedFiles,
    modules: &mut Vec<String>,
) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect_ts_files(root, &path, files, modules)?;
        } else if path.extension().is_some_and(|e| e == "ts") {
            let rel = path
                .strip_prefix(root)
                .expect("inside scratch")
                .to_path_buf();
            let module = rel.with_extension("").to_string_lossy().replace('\\', "/");
            let body = std::fs::read_to_string(&path)?;
            files.insert(rel, format!("// {GENERATED_MARKER}\n{body}"));
            modules.push(module);
        }
    }
    Ok(())
}

/// Generates the TypeScript bindings (§9.2) into memory: one file per type plus `index.ts`, every file
/// headed by the generated marker. `scratch` is an empty directory ts-rs may write into.
pub fn generate_typescript(scratch: &Path) -> Result<GeneratedFiles, Box<dyn std::error::Error>> {
    let cfg = ts_rs::Config::new()
        .with_out_dir(scratch)
        .with_large_int("number");
    export_ts_roots(&cfg)?;
    let mut files = GeneratedFiles::new();
    let mut modules = Vec::new();
    collect_ts_files(scratch, scratch, &mut files, &mut modules)?;
    modules.sort();
    let mut index = format!("// {GENERATED_MARKER}\n");
    for module in modules {
        index.push_str(&format!("export type * from \"./{module}\";\n"));
    }
    files.insert(PathBuf::from("index.ts"), index);
    Ok(files)
}
