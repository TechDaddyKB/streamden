/// A catalog lint finding (§9.7).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LintError {
    /// `operation:<name>`, `event:<type>` or `catalog`.
    pub subject: String,
    /// What is wrong.
    pub message: String,
}

impl fmt::Display for LintError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.subject, self.message)
    }
}

/// Errors of [`build`].
#[derive(Debug)]
pub enum BuildError {
    /// The catalog failed lint; nothing was generated.
    Lint(Vec<LintError>),
}

impl fmt::Display for BuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Lint(errors) => {
                writeln!(f, "catalog lint failed with {} finding(s):", errors.len())?;
                for e in errors {
                    writeln!(f, "  - {e}")?;
                }
                Ok(())
            }
        }
    }
}

impl std::error::Error for BuildError {}

/// MCP tool-name rule (§9.6): `^[a-z0-9_]{1,64}$`.
pub fn is_valid_mcp_tool_name(name: &str) -> bool {
    (1..=64).contains(&name.len())
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}

/// MCP property-name rule (§9.6): `^[A-Za-z0-9_.-]{1,64}$`.
pub fn is_valid_mcp_property_name(name: &str) -> bool {
    (1..=64).contains(&name.len())
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '-')
}

/// Maximum MCP tool description length (§9.6).
pub const MCP_DESCRIPTION_MAX: usize = 4096;

/// Lints the catalog (§9.7). Structural checks only; example validation against the generated schemas
/// is [`validate_examples`]. A [`Catalog`] holds **core** registrations (`register(&mut Catalog)`, §9.1):
/// plugin contributions arrive through manifests (§11) and never through it, so the reserved-prefix rule
/// of §4 applies to every entry.
pub fn lint(catalog: &Catalog) -> Vec<LintError> {
    let mut errors = Vec::new();
    let types: BTreeMap<String, Value> = catalog.peek_definitions().into_iter().collect();
    for (name, def) in catalog.operations() {
        let subject = format!("operation:{name}");
        let mut err = |message: String| {
            errors.push(LintError {
                subject: subject.clone(),
                message,
            })
        };
        if is_protocol_method(name.as_str()) {
            err("is a protocol method (§12), never a catalog operation".into());
        }
        if !is_reserved_slug(name.slug()) {
            err(format!(
                "core operation under the unreserved prefix {:?}: every namespace a core register(&mut Catalog) uses must be in RESERVED_SLUGS (§4)",
                name.slug()
            ));
        }
        if def.title.as_str().trim().is_empty() {
            err("missing title".into());
        }
        if def.description.as_str().trim().is_empty() {
            err("missing description".into());
        }
        if def.since.trim().is_empty() {
            err("missing `since`".into());
        }
        lint_object_root(def.params.as_value(), "params", &mut err);
        if let Some(props) = properties_of(def.params.as_value()) {
            for reserved in ["dryRun", "approvalId"] {
                if props.contains_key(reserved) {
                    err(format!(
                        "author params define the reserved param `{reserved}`"
                    ));
                }
            }
            for prop in props.keys() {
                if Catalog::is_mcp_exposed(def) && !is_valid_mcp_property_name(prop) {
                    err(format!(
                        "MCP property name {prop:?} violates ^[A-Za-z0-9_.-]{{1,64}}$"
                    ));
                }
            }
        }
        if def.tier >= RiskTier::REVERSIBLE_WRITE {
            lint_object_root(def.result.as_value(), "result (tier ≥ 1)", &mut err);
        }
        if let Some(props) = properties_of(def.result.as_value()) {
            for reserved in ["dryRun", "draft"] {
                if props.contains_key(reserved) {
                    err(format!(
                        "result schema defines the reserved result key `{reserved}`"
                    ));
                }
            }
        }
        if def.examples.is_empty() {
            err("needs at least one example".into());
        }
        let has = |shape: ResultShape| def.examples.iter().any(|e| e.shape == shape);
        if def.tier >= RiskTier::REVERSIBLE_WRITE && !has(ResultShape::DryRun) {
            err("tier ≥ 1 operations need a dry-run example".into());
        }
        if def.tier == RiskTier::CONFIG && !has(ResultShape::Draft) {
            err("tier-2 configuration operations need a draft example".into());
        }
        if def.tier < RiskTier::REVERSIBLE_WRITE && has(ResultShape::DryRun) {
            err("tier-0 operations have no dry-run result".into());
        }
        if def.tier != RiskTier::CONFIG && has(ResultShape::Draft) {
            err("only tier-2 configuration operations have a draft result".into());
        }
        for example in &def.examples {
            let has_dry_run = example
                .authored_params()
                .get("dryRun")
                .and_then(Value::as_bool)
                == Some(true);
            if (example.shape == ResultShape::DryRun) != has_dry_run {
                err(format!(
                    "example {:?}: `dryRun: true` in params must match the dry-run shape",
                    example.title
                ));
            }
            // A plan step's `params` are redacted against the named operation's schema (§3). A step
            // may name a target outside this catalog (a plugin operation, §8.1), but then its params
            // cannot be checked, so they must hold no value: publication redacts them whole otherwise.
            if example.shape != ResultShape::Normal
                && let Some(Value::Array(plan)) = example.authored_result().get("plan")
            {
                for (i, step) in plan.iter().enumerate() {
                    let operation = step.get("operation").and_then(Value::as_str);
                    let known = operation
                        .is_some_and(|op| catalog.operations().keys().any(|k| k.as_str() == op));
                    let empty = step.get("params").is_none_or(holds_no_value);
                    if !known && !empty {
                        err(format!(
                            "example {:?}: plan step {i} names {} outside this catalog with non-empty params, which cannot be checked for secrets",
                            example.title,
                            operation.map_or("no operation".to_string(), |op| format!("`{op}`"))
                        ));
                    }
                }
            }
        }
        if def.tier == RiskTier::DANGEROUS && def.expose.mcp {
            err("a core tier-4 operation must not be marked `expose.mcp` (D-030)".into());
        }
        if Catalog::is_mcp_exposed(def) {
            let tool = name.mcp_tool_name();
            if !is_valid_mcp_tool_name(&tool) {
                err(format!(
                    "MCP tool name {tool:?} violates ^[a-z0-9_]{{1,64}}$"
                ));
            }
            if def.description.as_str().len() > MCP_DESCRIPTION_MAX {
                err(format!(
                    "MCP description exceeds {MCP_DESCRIPTION_MAX} characters"
                ));
            }
        }
        lint_value_mode_enums(def.params.as_value(), "params", &types, &mut err);
        lint_secret_marks(def.params.as_value(), "params", &types, &mut err);
        lint_secret_marks(def.result.as_value(), "result", &types, &mut err);
        lint_untrusted_marks(def.params.as_value(), "params", &types, &mut err);
        lint_untrusted_marks(def.result.as_value(), "result", &types, &mut err);
    }
    let mut tool_names: BTreeMap<String, &OperationName> = BTreeMap::new();
    for (name, def) in catalog.operations() {
        if Catalog::is_mcp_exposed(def)
            && let Some(prev) = tool_names.insert(name.mcp_tool_name(), name)
        {
            errors.push(LintError {
                subject: format!("operation:{name}"),
                message: format!("MCP tool name collides with operation {prev}"),
            });
        }
    }
    for (r#type, def) in catalog.events() {
        let subject = format!("event:{type}");
        let mut err = |message: String| {
            errors.push(LintError {
                subject: subject.clone(),
                message,
            })
        };
        if !is_reserved_slug(r#type.slug()) {
            err(format!(
                "core event under the unreserved prefix {:?}: every namespace a core register(&mut Catalog) uses must be in RESERVED_SLUGS (§4)",
                r#type.slug()
            ));
        }
        if def.title.as_str().trim().is_empty() {
            err("missing title".into());
        }
        if def.description.as_str().trim().is_empty() {
            err("missing description".into());
        }
        if def.payload_version == 0 {
            err("payloadVersion starts at 1".into());
        }
        for message in lint_payload_versions(
            &catalog.payload_versions(r#type),
            def.payload_version,
            RPC_VERSION_MIN..=RPC_VERSION,
        ) {
            err(message);
        }
        lint_object_root(def.payload.as_value(), "payload", &mut err);
        if let Some(props) = properties_of(def.payload.as_value()) {
            for prop in props.keys() {
                if is_reserved_run_context_root(prop) {
                    err(format!(
                        "payload declares the reserved run-context root {prop:?}"
                    ));
                }
                if prop == RESERVED_FILTER_PATH_PLATFORM {
                    err(format!(
                        "payload declares a top-level {prop:?} field, the reserved filter path that resolves against the envelope (§6.2, A12)"
                    ));
                }
            }
            for filter in &def.filters {
                let head = filter.field.split('.').next().unwrap_or_default();
                if !props.contains_key(head) {
                    err(format!(
                        "filter field {:?} is not a payload property",
                        filter.field
                    ));
                }
            }
        }
        if def.examples.is_empty() {
            err("needs at least one example payload".into());
        }
        if !def.authored_examples.is_empty() && def.authored_examples.len() != def.examples.len() {
            err(format!(
                "authoredExamples ({}) must align with examples ({}); build typed examples with `push_typed_example`",
                def.authored_examples.len(),
                def.examples.len()
            ));
        }
        lint_secret_marks(def.payload.as_value(), "payload", &types, &mut err);
        lint_untrusted_marks(def.payload.as_value(), "payload", &types, &mut err);
    }
    for r#type in catalog.payload_versions_registered().keys() {
        if !catalog.events().contains_key(r#type) {
            errors.push(LintError {
                subject: format!("event:{type}"),
                message:
                    "payload version functions registered for an event type that is not registered"
                        .into(),
            });
        }
    }
    errors.extend(lint_shared_types(&types));
    errors
}

/// The payload-version lint of §5.2 and §9.7 (A13) for one event whose current `payloadVersion` is
/// `current` and whose build serves the `rpcVersion`s in `served`: the newest served `rpcVersion`
/// delivers the current `payloadVersion`, no `rpcVersion` delivers a newer one, and every step between
/// consecutive delivered versions has both its upgrade and its downgrade registered. Returns the
/// findings; [`lint`] calls it with the build's served range.
pub fn lint_payload_versions(
    versions: &crate::catalog::PayloadVersions,
    current: u32,
    served: std::ops::RangeInclusive<u32>,
) -> Vec<String> {
    let mut errors = Vec::new();
    let mut err = |message: String| errors.push(message);
    let newest = *served.end();
    for (rpc, version) in &versions.by_rpc_version {
        if !served.contains(rpc) {
            err(format!(
                "payloadVersions registers rpcVersion {rpc}, which this build does not serve ({}..={newest})",
                served.start()
            ));
        }
        if *version == 0 {
            err(format!(
                "payloadVersions maps rpcVersion {rpc} to payload version 0; payload versions start at 1"
            ));
        }
    }
    let table = versions.table_for(served, current);
    if table.get(&newest) != Some(&current) {
        err(format!(
            "payloadVersions maps the current rpcVersion {newest} to payload version {:?}, not the event's payloadVersion {current}",
            table.get(&newest)
        ));
    }
    for (rpc, version) in &table {
        if *version > current {
            err(format!(
                "payloadVersions maps rpcVersion {rpc} to payload version {version}, above the event's payloadVersion {current}"
            ));
        }
    }
    let delivered = crate::catalog::PayloadVersions::delivered(&table);
    for pair in delivered.windows(2) {
        let (from, to) = (pair[0], pair[1]);
        let step = versions.steps.get(&(from, to)).copied().unwrap_or_default();
        if step.upgrade.is_none() {
            err(format!(
                "payload version step {from} → {to} has no upgrade function registered (§5.2, A13: register_payload_upgrade)"
            ));
        }
        if step.downgrade.is_none() {
            err(format!(
                "payload version step {from} → {to} has no downgrade function registered (§5.2: register_payload_downgrade)"
            ));
        }
    }
    for (from, to) in versions.steps.keys() {
        if *to > current {
            err(format!(
                "payload version step {from} → {to} goes above the event's payloadVersion {current}"
            ));
        }
    }
    errors
}

/// The sibling flag a conditional field is gated on: `x-den-untrusted-flag`, else `untrusted` (§3).
pub fn untrusted_flag_of(property: &Map<String, Value>) -> Option<&str> {
    match property.get(UNTRUSTED_FLAG_KEY) {
        None => Some(UNTRUSTED_FLAG_DEFAULT),
        Some(Value::String(flag)) => Some(flag),
        Some(_) => None,
    }
}

/// Whether `schema` describes a boolean: `type: boolean`, or the required-nullable form of §3
/// (`anyOf: [boolean, null]` or `type: [boolean, null]`), following `$ref`s to shared types.
fn is_boolean_schema(schema: &Value, types: &BTreeMap<String, Value>) -> bool {
    let Some(obj) = schema.as_object() else {
        return false;
    };
    if let Some(target) = resolve_ref(obj, types) {
        return is_boolean_schema(target, types);
    }
    match obj.get("type") {
        Some(Value::String(t)) => return t == "boolean",
        Some(Value::Array(ts)) => {
            return ts.iter().all(|t| t == "boolean" || t == "null")
                && ts.iter().any(|t| t == "boolean");
        }
        _ => {}
    }
    if let Some(Value::Array(branches)) = obj.get("anyOf").or_else(|| obj.get("oneOf")) {
        return !branches.is_empty()
            && branches
                .iter()
                .all(|b| b == &json!({ "type": "null" }) || is_boolean_schema(b, types))
            && branches.iter().any(|b| b != &json!({ "type": "null" }));
    }
    false
}

/// Lints the `x-den-untrusted` marks of a schema (§3, §9.7): a mark is `true` or `"conditional"`; a
/// conditional mark sits on a property whose object also has the flag it names (`x-den-untrusted-flag`,
/// default `untrusted`) as a boolean or required-nullable boolean property; the flag annotation only
/// goes with a conditional mark.
fn lint_untrusted_marks(
    schema: &Value,
    path: &str,
    types: &BTreeMap<String, Value>,
    err: &mut impl FnMut(String),
) {
    for_each_subschema(schema, path, &mut |at, obj| {
        match obj.get("x-den-untrusted") {
            None | Some(Value::Bool(true)) => {}
            Some(Value::String(s)) if s == UNTRUSTED_CONDITIONAL => {
                let under_properties = at
                    .rsplit('/')
                    .nth(1)
                    .is_some_and(|parent| parent == "properties");
                if !under_properties {
                    err(format!(
                        "{at}: `x-den-untrusted: \"conditional\"` must sit on a property, next to the boolean flag that gates it (§3)"
                    ));
                }
            }
            Some(other) => err(format!(
                "{at}: x-den-untrusted must be `true` or \"conditional\", got {other}"
            )),
        }
        if obj.contains_key(UNTRUSTED_FLAG_KEY)
            && obj.get("x-den-untrusted") != Some(&Value::String(UNTRUSTED_CONDITIONAL.into()))
        {
            err(format!(
                "{at}: `{UNTRUSTED_FLAG_KEY}` only goes with `x-den-untrusted: \"conditional\"` (§3)"
            ));
        }
        let Some(Value::Object(props)) = obj.get("properties") else {
            return;
        };
        for (name, prop) in props {
            let Some(prop_obj) = prop.as_object() else {
                continue;
            };
            if prop_obj.get("x-den-untrusted") != Some(&Value::String(UNTRUSTED_CONDITIONAL.into()))
            {
                continue;
            }
            let Some(flag) = untrusted_flag_of(prop_obj) else {
                err(format!(
                    "{at}/properties/{name}: `{UNTRUSTED_FLAG_KEY}` must be a string naming a sibling property"
                ));
                continue;
            };
            match props.get(flag) {
                None => err(format!(
                    "{at}/properties/{name}: conditional field names the sibling flag {flag:?}, which the object does not declare (§3, §9.7)"
                )),
                Some(sibling) if !is_boolean_schema(sibling, types) => err(format!(
                    "{at}/properties/{name}: the sibling flag {flag:?} must be a boolean or required-nullable boolean property (§3, §9.7)"
                )),
                Some(_) => {}
            }
        }
    });
}

/// The `x-secret` lint over every shared type. [`lint`] runs it on the catalog as registered;
/// [`build_unredacted`] runs it again on the final table, which also holds the types registered while
/// building (result shapes, `TemplateString`, …).
fn lint_shared_types(types: &BTreeMap<String, Value>) -> Vec<LintError> {
    let mut errors = Vec::new();
    for (name, schema) in types {
        let subject = format!("type:{name}");
        let mut err = |message: String| {
            errors.push(LintError {
                subject: subject.clone(),
                message,
            })
        };
        lint_secret_marks(schema, "", types, &mut err);
        lint_untrusted_marks(schema, "", types, &mut err);
    }
    errors
}

/// Calls `f` with every schema object reachable from `schema` through the applicator keywords, and the
/// pointer-like path it sits at.
fn for_each_subschema(schema: &Value, path: &str, f: &mut dyn FnMut(&str, &Map<String, Value>)) {
    let Some(obj) = schema.as_object() else {
        return;
    };
    f(path, obj);
    for_each_child_schema(obj, path, &mut |at, child| for_each_subschema(child, at, f));
}

/// Visits immediate schema children without treating annotation values as schemas.
fn for_each_child_schema(obj: &Map<String, Value>, path: &str, f: &mut impl FnMut(&str, &Value)) {
    for (key, member) in obj {
        match key.as_str() {
            "properties" | "patternProperties" | "dependentSchemas" | "$defs" | "definitions" => {
                if let Some(entries) = member.as_object() {
                    for (name, child) in entries {
                        f(&format!("{path}/{key}/{name}"), child);
                    }
                }
            }
            "allOf" | "anyOf" | "oneOf" | "prefixItems" => {
                if let Some(branches) = member.as_array() {
                    for (i, child) in branches.iter().enumerate() {
                        f(&format!("{path}/{key}/{i}"), child);
                    }
                }
            }
            // `items` is one schema in 2020-12 and may be a tuple array in draft-07 input.
            "items" if member.is_array() => {
                for (i, child) in member.as_array().into_iter().flatten().enumerate() {
                    f(&format!("{path}/{key}/{i}"), child);
                }
            }
            "additionalProperties"
            | "unevaluatedProperties"
            | "items"
            | "contains"
            | "unevaluatedItems"
            | "contentSchema"
            | "if"
            | "then"
            | "else"
            | "not"
            | "propertyNames" => {
                f(&format!("{path}/{key}"), member);
            }
            _ => {}
        }
    }
}

/// Lints the `x-secret` marks of a schema (§3). A mark must be the boolean `true` (publication fails
/// closed on anything else, but the author should hear about it first). `x-secret: false` is rejected
/// wherever it appears: §3 defines the mark only as `true`, secrecy is monotonic so a `false` clears
/// nothing, and the one effect it can have is to hide a mark, by misleading a reader when it sits
/// beside a `$ref` to a marked type, or by erasing one outright when `#[schemars(extend(...))]` on a
/// field replaces the keys an `#[schemars(inline)]` type's schema carried, before this crate sees the
/// schema at all.
fn lint_secret_marks(
    schema: &Value,
    path: &str,
    types: &BTreeMap<String, Value>,
    err: &mut impl FnMut(String),
) {
    for_each_subschema(schema, path, &mut |at, obj| {
        if obj.contains_key("$ref") && ref_name(obj).is_none() {
            err(format!(
                "{at}: $ref must use the canonical `#/types/<Name>` prefix (§9.1)"
            ));
        }
        match obj.get("x-secret") {
            None | Some(Value::Bool(true)) => {}
            Some(Value::Bool(false)) => {
                let marked = ref_name(obj).and_then(|name| referenced_secret_type(&name, types));
                match marked {
                    Some(marked) => err(format!(
                        "{at}: `x-secret: false` beside a $ref to `{marked}`, which is marked secret; secrecy is monotonic (§3) and the mark cannot be cleared here: drop the sibling"
                    )),
                    None => err(format!(
                        "{at}: `x-secret: false` has no effect (§3 marks with `true` only; secrecy is monotonic) and a field-level `extend` can erase an inline type's mark with it: drop it"
                    )),
                }
            }
            Some(other) => err(format!("{at}: x-secret must be a boolean, got {other}")),
        }
    });
    lint_secret_literals(schema, path, types, false, &mut Default::default(), err);
}

/// Schema literals are published verbatim. A whole-value mark also protects every descendant and
/// referenced type, including siblings of a mark in a same-value composition. Never print literals
/// in diagnostics. Track reference cycles on the current path so recursive types terminate.
fn lint_secret_literals(
    schema: &Value,
    path: &str,
    types: &BTreeMap<String, Value>,
    inherited_secret: bool,
    visiting: &mut std::collections::BTreeSet<String>,
    err: &mut impl FnMut(String),
) {
    let Some(obj) = schema.as_object() else {
        return;
    };
    let mut refs = Vec::new();
    let secret = inherited_secret
        || marks_whole_value(schema, &mut refs)
        || refs
            .iter()
            .any(|name| referenced_secret_type(name, types).is_some());
    if secret {
        for key in ["default", "examples", "const", "enum"] {
            if obj.contains_key(key) {
                err(format!(
                    "{path}/{key}: `{key}` is forbidden under a secret-marked position (§3)"
                ));
            }
        }
        if let Some(name) = ref_name(obj)
            && let Some(target) = types.get(&name)
            && visiting.insert(name.clone())
        {
            lint_secret_literals(
                target,
                &format!("{path}/$ref/{name}"),
                types,
                true,
                visiting,
                err,
            );
            visiting.remove(&name);
        }
    }
    for_each_child_schema(obj, path, &mut |at, child| {
        lint_secret_literals(child, at, types, secret, visiting, err);
    });
}

/// The first shared type reachable from `name` whose schema marks the whole value secret (or carries
/// a malformed mark, which publication treats as secret), if any. Reachable means through `$ref`s and
/// through the applicators that apply to the same value (`allOf`/`anyOf`/`oneOf`, `if`/`then`/`else`,
/// `not`), the way the publication walk unions them. Cycles are visited once.
fn referenced_secret_type(name: &str, types: &BTreeMap<String, Value>) -> Option<String> {
    let mut seen = std::collections::BTreeSet::new();
    let mut pending = vec![name.to_owned()];
    while let Some(current) = pending.pop() {
        if !seen.insert(current.clone()) {
            continue;
        }
        let Some(target) = types.get(&current) else {
            continue;
        };
        let mut refs = Vec::new();
        if marks_whole_value(target, &mut refs) {
            return Some(current);
        }
        pending.extend(refs);
    }
    None
}

/// Whether `schema` marks the whole value it applies to: an `x-secret` that is not `false` on it or on
/// a subschema that applies to the same value. The `$ref`s met on the way are collected into `refs`
/// for the caller to follow.
fn marks_whole_value(schema: &Value, refs: &mut Vec<String>) -> bool {
    let Some(obj) = schema.as_object() else {
        return false;
    };
    if obj
        .get("x-secret")
        .is_some_and(|mark| *mark != Value::Bool(false))
    {
        return true;
    }
    if let Some(name) = ref_name(obj) {
        refs.push(name);
    }
    let branches = ["allOf", "anyOf", "oneOf"]
        .into_iter()
        .filter_map(|key| obj.get(key)?.as_array())
        .flatten();
    let singles = ["if", "then", "else", "not"]
        .into_iter()
        .filter_map(|key| obj.get(key));
    let mut marked = false;
    for sub in branches.chain(singles) {
        marked |= marks_whole_value(sub, refs);
    }
    marked
}

fn properties_of(schema: &Value) -> Option<&Map<String, Value>> {
    schema.get("properties").and_then(Value::as_object)
}

fn lint_object_root(schema: &Value, what: &str, err: &mut impl FnMut(String)) {
    let Some(obj) = schema.as_object() else {
        err(format!(
            "{what} root must be a schema object with `type: object`"
        ));
        return;
    };
    if obj.get("type").and_then(Value::as_str) != Some("object") {
        err(format!("{what} root must be `type: object`"));
    }
    for key in ["oneOf", "anyOf", "allOf"] {
        if obj.contains_key(key) {
            err(format!("{what} root must not use `{key}` (§9.6)"));
        }
    }
}

/// The string members of a closed enum schema, whichever form it takes: `enum: [...]`, `const`, or a
/// `oneOf`/`anyOf` whose branches are all `const` strings (what schemars emits for documented unit
/// variants).
fn enum_members(obj: &Map<String, Value>) -> Option<Vec<String>> {
    if let Some(Value::Array(members)) = obj.get("enum") {
        return Some(
            members
                .iter()
                .filter_map(Value::as_str)
                .map(str::to_owned)
                .collect(),
        );
    }
    if let Some(Value::String(c)) = obj.get("const") {
        return Some(vec![c.clone()]);
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(Value::Array(branches)) = obj.get(key)
            && !branches.is_empty()
        {
            let consts: Vec<String> = branches
                .iter()
                .filter_map(|b| b.get("const").and_then(Value::as_str).map(str::to_owned))
                .collect();
            if consts.len() == branches.len() {
                return Some(consts);
            }
        }
    }
    None
}

fn lint_value_mode_enums(
    schema: &Value,
    path: &str,
    types: &BTreeMap<String, Value>,
    err: &mut impl FnMut(String),
) {
    let Some(obj) = schema.as_object() else {
        return;
    };
    if let Some(mode) = obj.get("x-den-template") {
        match TemplateMode::from_json(mode) {
            None => err(format!(
                "{path}: x-den-template must be false, \"text\" or \"value\", got {mode}"
            )),
            Some(TemplateMode::Text)
                if obj.get("type").and_then(Value::as_str) != Some("string") =>
            {
                err(format!(
                    "{path}: x-den-template \"text\" applies to `type: string` leaves only (§10.1)"
                ))
            }
            _ => {}
        }
    }
    let target = resolve_ref(obj, types)
        .and_then(Value::as_object)
        .unwrap_or(obj);
    if enum_members(target).is_some_and(|members| members.iter().any(|m| m.starts_with('{'))) {
        err(format!(
            "{path}: enum member starts with `{{`, which a value-mode field treats as a template (§10.1)"
        ));
    }
    if let Some(props) = properties_of(schema) {
        for (name, prop) in props {
            lint_value_mode_enums(prop, &format!("{path}/{name}"), types, err);
        }
    }
    for key in ["items", "additionalProperties"] {
        if let Some(child) = obj.get(key)
            && child.is_object()
        {
            lint_value_mode_enums(child, &format!("{path}/{key}"), types, err);
        }
    }
    for key in ["prefixItems", "oneOf", "anyOf", "allOf"] {
        if let Some(Value::Array(branches)) = obj.get(key) {
            for (i, branch) in branches.iter().enumerate() {
                lint_value_mode_enums(branch, &format!("{path}/{key}/{i}"), types, err);
            }
        }
    }
}

/// Template modes of §10.1.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TemplateMode {
    /// Literal, never parsed.
    Literal,
    /// Mixed text and `{…}` forms; always renders to a string.
    Text,
    /// Exactly one `{…}` form; the rendered JSON value replaces the field.
    Value,
}

impl TemplateMode {
    fn to_json(self) -> Value {
        match self {
            Self::Literal => Value::Bool(false),
            Self::Text => Value::String("text".into()),
            Self::Value => Value::String("value".into()),
        }
    }

    fn from_json(value: &Value) -> Option<Self> {
        match value {
            Value::Bool(false) => Some(Self::Literal),
            Value::String(s) if s == "text" => Some(Self::Text),
            Value::String(s) if s == "value" => Some(Self::Value),
            _ => None,
        }
    }
}

/// Resolves a leaf's template mode (§10.1): an explicit `x-den-template` wins; otherwise numbers,
/// integers, booleans and enum strings are `value`, strings with `x-ui.variables: true` are `text`, and
/// everything else is literal. A `const` is a literal: it is a discriminator or a fixed value, and a
/// template there could never be resolved at save time. A `$ref` resolves through the referenced type
/// with the property's own hints (`x-ui`, `x-den-template`) kept, so a shared string newtype on a
/// variable-enabled field is `text`.
pub fn resolve_template_mode(leaf: &Value, types: &BTreeMap<String, Value>) -> TemplateMode {
    resolve_mode(leaf, types, 0)
}

/// Bound on `$ref` chains followed while resolving one leaf (a `$ref` whose target is itself a `$ref`).
const MAX_REF_DEPTH: usize = 16;

fn resolve_mode(leaf: &Value, types: &BTreeMap<String, Value>, depth: usize) -> TemplateMode {
    let Some(obj) = leaf.as_object() else {
        return TemplateMode::Literal;
    };
    if let Some(explicit) = obj.get("x-den-template").and_then(TemplateMode::from_json) {
        return explicit;
    }
    if let Some(target) = resolve_ref(obj, types) {
        if depth >= MAX_REF_DEPTH {
            return TemplateMode::Literal;
        }
        // A read-only view for deciding the mode: the target with the property's own keys laid over
        // it. Never published, so keyword scope is no concern here (see `merge_ref_target`).
        let mut view = target.as_object().cloned().unwrap_or_default();
        for (key, value) in obj {
            if key != "$ref" && key != "x-secret" {
                view.insert(key.clone(), value.clone());
            }
        }
        return resolve_mode(&Value::Object(view), types, depth + 1);
    }
    if obj.contains_key("const") {
        return TemplateMode::Literal;
    }
    if enum_members(obj).is_some() {
        return TemplateMode::Value;
    }
    let ty = obj.get("type").and_then(Value::as_str);
    match ty {
        Some("number" | "integer" | "boolean") => TemplateMode::Value,
        Some("string") => {
            let variables = obj
                .get("x-ui")
                .and_then(|ui| ui.get("variables"))
                .and_then(Value::as_bool)
                .unwrap_or(false);
            if variables {
                TemplateMode::Text
            } else {
                TemplateMode::Literal
            }
        }
        _ => TemplateMode::Literal,
    }
}

fn ref_name(obj: &Map<String, Value>) -> Option<String> {
    let r = obj.get("$ref")?.as_str()?;
    r.strip_prefix("#/types/").map(str::to_owned)
}

fn resolve_ref<'a>(
    obj: &Map<String, Value>,
    types: &'a BTreeMap<String, Value>,
) -> Option<&'a Value> {
    types.get(&ref_name(obj)?)
}

/// Keys that annotate a schema rather than constrain it (plus every `x-` extension).
pub(crate) fn is_annotation_key(key: &str) -> bool {
    matches!(
        key,
        "description"
            | "title"
            | "default"
            | "examples"
            | "deprecated"
            | "readOnly"
            | "writeOnly"
            | "$comment"
    ) || key.starts_with("x-")
}

/// Inlines a `$ref` property: the referenced schema with the property's siblings applied, every keyword
/// keeping the scope it had. JSON Schema 2020-12 applies `$ref` siblings in conjunction with the target,
/// and keywords interact only within their own schema object (`additionalProperties` exempts the
/// `properties` beside it, `items` the `prefixItems` beside it, …), so a validation sibling must never
/// be moved beside the target's keywords: with any validation sibling present the target is kept whole
/// as `allOf: [target]` and the siblings stay in the outer object, exactly the shape `{ "$ref", … }` had
/// (Codex round 5). A sibling `allOf` of the property's own takes the target as one more member, so the
/// sibling's branches stay in force; a sibling `allOf` that is not an array cannot take it, so the
/// `$ref` is kept beside it and nothing is dropped (publication fails closed on the malformed keyword).
/// Annotations ([`is_annotation_key`]) interact with nothing and are laid over the target's: a
/// property's `description` replaces the target's. `x-secret` is the exception among the annotations:
/// secrecy is monotonic (§3), so the merged mark is [`merged_secret_mark`] of both sides and a `false`
/// sibling never clears the target's `true`.
pub fn merge_ref_target(property: &Map<String, Value>, target: &Value) -> Map<String, Value> {
    let mark = merged_secret_mark(property.get("x-secret"), target.get("x-secret"));
    let (annotations, constraints): (Vec<_>, Vec<_>) = property
        .iter()
        .filter(|(key, _)| *key != "$ref" && *key != "x-secret")
        .partition(|(key, _)| is_annotation_key(key));
    let mut merged = if constraints.is_empty() {
        target.as_object().cloned().unwrap_or_default()
    } else {
        // The target's own annotations are lifted too (they interact with nothing); its validation
        // keywords stay in their own schema object.
        let mut outer: Map<String, Value> = target
            .as_object()
            .into_iter()
            .flatten()
            .filter(|(key, _)| is_annotation_key(key) && *key != "x-secret")
            .map(|(key, value)| (key.clone(), value.clone()))
            .collect();
        outer.extend(
            constraints
                .into_iter()
                .map(|(key, value)| (key.clone(), value.clone())),
        );
        match outer.get_mut("allOf") {
            Some(Value::Array(all_of)) => all_of.insert(0, target.clone()),
            Some(_) => {
                if let Some(reference) = property.get("$ref") {
                    outer.insert("$ref".into(), reference.clone());
                }
            }
            None => {
                outer.insert("allOf".into(), json!([target.clone()]));
            }
        }
        outer
    };
    for (key, value) in annotations {
        merged.insert(key.clone(), value.clone());
    }
    match mark {
        Some(mark) => {
            merged.insert("x-secret".into(), mark);
        }
        None => {
            merged.remove("x-secret");
        }
    }
    merged
}

/// The `x-secret` mark of two schemas that apply to the same position, in conjunction (§3). Secrecy is
/// monotonic: `true` on either side wins over `false`, and a malformed (non-boolean) mark on either
/// side is kept as it is, so the publication walk still fails closed on it instead of seeing a clean
/// boolean. `None` only when neither side carries a mark.
pub(crate) fn merged_secret_mark(a: Option<&Value>, b: Option<&Value>) -> Option<Value> {
    let marks: Vec<&Value> = [a, b].into_iter().flatten().collect();
    if let Some(malformed) = marks.iter().find(|m| !m.is_boolean()) {
        return Some((*malformed).clone());
    }
    if marks.is_empty() {
        return None;
    }
    Some(Value::Bool(marks.iter().any(|m| m.as_bool() == Some(true))))
}

/// Derives the invocation and authoring schemas of an operation from its author params (§10.1).
/// Returns `(params, paramsAuthoring)`: both carry a resolved `x-den-template` on every leaf; in
/// `paramsAuthoring` every value-mode leaf becomes `anyOf: [<concrete>, TemplateString]`. Nesting is
/// preserved through objects, arrays, composition branches (`oneOf`/`anyOf`/`allOf`, so tagged unions
/// get their leaves derived) and references to structured shared types, which are inlined with the
/// property's own siblings merged in; discriminator `const`s stay literal.
pub fn derive_param_schemas(params: &Schema, types: &BTreeMap<String, Value>) -> (Schema, Schema) {
    let mut invocation = params.clone().to_value();
    let mut authoring = params.clone().to_value();
    annotate_leaves(&mut invocation, types, false, &mut Vec::new());
    annotate_leaves(&mut authoring, types, true, &mut Vec::new());
    (
        Schema::try_from(invocation).expect("object"),
        Schema::try_from(authoring).expect("object"),
    )
}

/// Whether a schema has structure to descend into: an object, an array or a composition. An enum
/// written as `oneOf` of `const`s (schemars' form for documented unit variants) is a leaf.
fn is_structured(obj: &Map<String, Value>) -> bool {
    if enum_members(obj).is_some() {
        return false;
    }
    matches!(
        obj.get("type").and_then(Value::as_str),
        Some("object" | "array")
    ) || [
        "properties",
        "patternProperties",
        "additionalProperties",
        "items",
        "prefixItems",
        "oneOf",
        "anyOf",
        "allOf",
    ]
    .iter()
    .any(|k| obj.contains_key(*k))
}

/// Whether `obj` is the `TemplateString` schema (§10.1), or a schema that already admits it as an
/// `anyOf` branch (`TemplateOr<T>`): such a field is value mode and already widened.
fn is_template_string(obj: &Map<String, Value>) -> bool {
    obj.get("type").and_then(Value::as_str) == Some("string")
        && obj.get("pattern").and_then(Value::as_str)
            == Some(crate::template::TEMPLATE_STRING_PATTERN)
}

fn admits_template_string(obj: &Map<String, Value>) -> bool {
    obj.get("anyOf")
        .and_then(Value::as_array)
        .is_some_and(|branches| {
            branches
                .iter()
                .any(|b| b.as_object().is_some_and(is_template_string))
        })
}

/// `visiting` holds the names of shared types currently being inlined, so a recursive type keeps its
/// `$ref` instead of recursing forever.
fn annotate_leaves(
    schema: &mut Value,
    types: &BTreeMap<String, Value>,
    authoring: bool,
    visiting: &mut Vec<String>,
) {
    let Some(obj) = schema.as_object_mut() else {
        return;
    };
    let explicit = obj.get("x-den-template").and_then(TemplateMode::from_json);
    // A `$ref` to a structured shared type is inlined (siblings kept) so its leaves can be derived; a
    // `$ref` to a leaf type keeps the reference and resolves its mode through the target.
    if let Some(name) = ref_name(obj) {
        match types.get(&name) {
            Some(target) if target.as_object().is_some_and(is_structured) => {
                if visiting.contains(&name) {
                    obj.insert("x-den-template".into(), Value::Bool(false));
                    return;
                }
                let mut inlined = Value::Object(merge_ref_target(obj, target));
                visiting.push(name);
                annotate_leaves(&mut inlined, types, authoring, visiting);
                visiting.pop();
                *schema = inlined;
            }
            _ => annotate_leaf(schema, types, authoring),
        }
        return;
    }
    if is_structured(obj) {
        // `anyOf: [T, TemplateString]` (a `TemplateOr<T>` field) is value mode and already widened,
        // whether or not the author also said `"value"` explicitly.
        let already_widened =
            matches!(explicit, None | Some(TemplateMode::Value)) && admits_template_string(obj);
        let mode = if already_widened {
            TemplateMode::Value
        } else {
            explicit.unwrap_or(TemplateMode::Literal)
        };
        obj.insert("x-den-template".into(), mode.to_json());
        if already_widened {
            return;
        }
        if mode == TemplateMode::Value {
            if authoring {
                widen_to_template(schema);
            }
            return;
        }
        for key in ["properties", "patternProperties"] {
            if let Some(Value::Object(props)) = obj.get_mut(key) {
                for prop in props.values_mut() {
                    annotate_leaves(prop, types, authoring, visiting);
                }
            }
        }
        for key in ["additionalProperties", "items"] {
            if let Some(child) = obj.get_mut(key)
                && child.is_object()
            {
                annotate_leaves(child, types, authoring, visiting);
            }
        }
        for key in ["prefixItems", "oneOf", "anyOf", "allOf"] {
            if let Some(Value::Array(branches)) = obj.get_mut(key) {
                for branch in branches {
                    // A branch that only constrains (`{ "maxProperties": 1 }`, `{ "required": [...] }`)
                    // describes no leaf of its own and gets no mode.
                    if branch.as_object().is_some_and(describes_a_value) {
                        annotate_leaves(branch, types, authoring, visiting);
                    }
                }
            }
        }
        return;
    }
    annotate_leaf(schema, types, authoring);
}

/// Whether a schema says what kind of value it describes (as opposed to a bare constraint fragment).
fn describes_a_value(obj: &Map<String, Value>) -> bool {
    obj.contains_key("type")
        || obj.contains_key("$ref")
        || obj.contains_key("enum")
        || is_structured(obj)
}

fn annotate_leaf(schema: &mut Value, types: &BTreeMap<String, Value>, authoring: bool) {
    let mode = resolve_template_mode(schema, types);
    let Some(obj) = schema.as_object_mut() else {
        return;
    };
    obj.insert("x-den-template".into(), mode.to_json());
    if authoring && mode == TemplateMode::Value && !is_template_string(obj) {
        widen_to_template(schema);
    }
}

fn widen_to_template(schema: &mut Value) {
    let Some(obj) = schema.as_object_mut() else {
        return;
    };
    let description = obj.remove("description");
    let mut concrete = std::mem::take(obj);
    concrete.remove("x-den-template");
    let mut widened = Map::new();
    if let Some(desc) = description {
        widened.insert("description".into(), desc);
    }
    widened.insert(
        "anyOf".into(),
        json!([Value::Object(concrete), template_string_schema().to_value()]),
    );
    widened.insert("x-den-template".into(), Value::String("value".into()));
    *obj = widened;
}

pub use crate::secret::REDACTED;

/// Bound on value nesting followed while redacting one value; a value nested deeper is redacted whole.
const MAX_REDACT_DEPTH: usize = 64;

/// Bound on the subschemas that may apply at one instance location once `$ref` chains, composition
/// branches and conditionals are expanded; a position that needs more is redacted whole.
const MAX_APPLICABLE: usize = 512;

/// Redacts every value at an `x-secret: true` position of `schema` to `"***"` (§3), so examples never
/// publish a secret. The walk is structurally fail-closed rather than keyword-by-keyword:
///
/// - At every instance location the **union** of every subschema that could apply is consulted: the
///   schema itself, the targets of its `$ref` chain (followed to the end; a cycle is visited once),
///   every `allOf`/`anyOf`/`oneOf` branch, `if`, `then` *and* `else`, `not`, and every
///   `dependentSchemas` entry, whether or not that branch would validate the value. A secret marked in
///   any of them redacts the value. A branch that does not apply can only redact more, never less.
/// - Object members collect their schemas from every applicable subschema: the named `properties`
///   entry **and** every matching `patternProperties` entry, and when neither matched in that
///   subschema its `additionalProperties` and `unevaluatedProperties` (whatever another subschema
///   evaluated: the walk never decides which branch validated). Whether a pattern matches a member
///   name is decided by the JSON Schema validator itself ([`PatternProbes`]): the same ECMA-262
///   dialect, engine and limits that validate the authored examples, so the two can never disagree
///   about which entry applies; a pattern the validator rejects cannot be classified, so every member
///   of that object redacts whole. Array items collect `prefixItems[i]`, else `items`, else
///   `unevaluatedItems`, plus `contains` always.
/// - Anything the walk cannot classify redacts the value whole instead of passing it through: a `$ref`
///   that does not resolve to a shared type, an expansion past [`MAX_APPLICABLE`] subschemas, a value
///   nested past [`MAX_REDACT_DEPTH`], a schema keyword this walk does not model, a keyword whose
///   value has the wrong shape, or an `x-secret` that is not a boolean.
///
/// Values the schema does not describe at all (a member of an untyped `params` object, for instance)
/// are left alone: an unmarked position is not a secret.
pub fn redact_secrets(value: &mut Value, schema: &Value, types: &BTreeMap<String, Value>) {
    redact(value, &[schema], types, 0, &mut PatternProbes::default());
}

/// Decides whether a `patternProperties` entry applies to a member name by asking the JSON Schema
/// validator that checks the authored examples, rather than a regex engine of this crate's own. The
/// validator implements the ECMA-262 dialect JSON Schema prescribes (`\w` and `\W` are ASCII there,
/// `\s` includes U+FEFF, …) on top of its engine and limits; a second engine, however carefully
/// configured, would be a second opinion. One probe schema `{ "patternProperties": { <pattern>: false } }`
/// is compiled per pattern: the member `{ <name>: null }` fails it exactly when the pattern selects the
/// name. A pattern the validator cannot compile is `None`: the caller cannot classify the members and
/// fails closed.
#[derive(Default)]
struct PatternProbes(BTreeMap<String, Option<jsonschema::Validator>>);

impl PatternProbes {
    fn applies(&mut self, pattern: &str, name: &str) -> Option<bool> {
        let probe = self.0.entry(pattern.to_owned()).or_insert_with(|| {
            let mut entries = Map::new();
            entries.insert(pattern.to_owned(), Value::Bool(false));
            let mut schema = Map::new();
            schema.insert("patternProperties".into(), Value::Object(entries));
            jsonschema::validator_for(&Value::Object(schema)).ok()
        });
        let validator = probe.as_ref()?;
        let mut instance = Map::new();
        instance.insert(name.to_owned(), Value::Null);
        Some(!validator.is_valid(&Value::Object(instance)))
    }
}

/// Why a position could not be classified. Every case redacts the value whole.
#[derive(Debug)]
enum Unclassifiable {
    /// A `$ref` that is not `#/types/<Name>` or names no shared type.
    UnresolvedRef,
    /// More than [`MAX_APPLICABLE`] subschemas apply at one location.
    Exhausted,
    /// A schema position that is neither an object nor a boolean.
    NotASchema,
    /// A keyword the walk does not model, or a modelled keyword with a value of the wrong shape.
    UnknownKeyword,
    /// `x-secret` with a non-boolean value.
    MalformedSecretMark,
}

/// Keywords this walk models, each with the value shape it accepts. Everything else that is not an
/// annotation ([`is_annotation_key`]) is unknown and fails closed.
fn check_keyword(key: &str, value: &Value) -> Result<(), Unclassifiable> {
    let ok = match key {
        // Identifiers and reserved locations: no effect on the instance at this location.
        "$schema" | "$id" | "$anchor" | "$vocabulary" | "$dynamicAnchor" => true,
        "$defs" | "definitions" => value.is_object(),
        "$ref" => value.is_string(),
        // Validation keywords without subschemas.
        "type" | "enum" | "const" | "multipleOf" | "maximum" | "exclusiveMaximum" | "minimum"
        | "exclusiveMinimum" | "maxLength" | "minLength" | "pattern" | "maxItems" | "minItems"
        | "uniqueItems" | "maxContains" | "minContains" | "maxProperties" | "minProperties"
        | "required" | "dependentRequired" | "format" | "contentMediaType" | "contentEncoding" => {
            true
        }
        // `contentSchema` describes the *decoded* content of a string: a mark inside it names a secret
        // this walk cannot see, so only the boolean form (no marks possible) is modelled.
        "contentSchema" => value.is_boolean(),
        // Applicators at this location.
        "allOf" | "anyOf" | "oneOf" => value.is_array(),
        // `propertyNames` constrains keys, which are published as-is: a mark in it redacts the object.
        "if" | "then" | "else" | "not" | "propertyNames" => value.is_object() || value.is_boolean(),
        "dependentSchemas" => value.is_object(),
        // Applicators for children.
        "properties" | "patternProperties" => value.is_object(),
        "additionalProperties"
        | "unevaluatedProperties"
        | "items"
        | "contains"
        | "unevaluatedItems" => value.is_object() || value.is_boolean(),
        "prefixItems" => value.is_array(),
        other => is_annotation_key(other),
    };
    if ok {
        Ok(())
    } else {
        Err(Unclassifiable::UnknownKeyword)
    }
}

/// Every subschema that applies at one instance location, expanded from `roots` (§3): `$ref` targets
/// (chains followed completely, each shared type visited once per location), composition branches,
/// both conditional branches and the condition itself, `not`, and `dependentSchemas` entries. Boolean
/// schemas carry no marks and no children and are dropped. The expansion is a union: it never decides
/// which branch validates. Every keyword of every subschema is checked on the way.
fn applicable<'a>(
    roots: &[&'a Value],
    types: &'a BTreeMap<String, Value>,
) -> Result<Vec<&'a Map<String, Value>>, Unclassifiable> {
    let mut out: Vec<&'a Map<String, Value>> = Vec::new();
    let mut seen_refs: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    let mut stack: Vec<&'a Value> = roots.iter().rev().copied().collect();
    while let Some(schema) = stack.pop() {
        let obj = match schema {
            Value::Bool(_) => continue,
            Value::Object(obj) => obj,
            _ => return Err(Unclassifiable::NotASchema),
        };
        if out.len() >= MAX_APPLICABLE {
            return Err(Unclassifiable::Exhausted);
        }
        out.push(obj);
        for (key, member) in obj {
            check_keyword(key, member)?;
            match key.as_str() {
                "$ref" => {
                    let name = shared_type_name(obj).ok_or(Unclassifiable::UnresolvedRef)?;
                    let target = types.get(&name).ok_or(Unclassifiable::UnresolvedRef)?;
                    if seen_refs.insert(name) {
                        stack.push(target);
                    }
                }
                "allOf" | "anyOf" | "oneOf" => {
                    if let Some(branches) = member.as_array() {
                        stack.extend(branches.iter().rev());
                    }
                }
                "if" | "then" | "else" | "not" | "propertyNames" => stack.push(member),
                "dependentSchemas" => {
                    if let Some(entries) = member.as_object() {
                        stack.extend(entries.values().rev());
                    }
                }
                _ => {}
            }
        }
    }
    Ok(out)
}

/// The shared type a `$ref` names, and nothing else: `protocol.json` has no other reference target,
/// so a pointer anywhere else (a local `$defs`, the document root, another document) is unresolvable.
fn shared_type_name(obj: &Map<String, Value>) -> Option<String> {
    obj.get("$ref")?
        .as_str()?
        .strip_prefix("#/types/")
        .map(str::to_owned)
}

/// Whether any applicable subschema marks this position secret; a non-boolean mark is unclassifiable.
fn marked_secret(applicable: &[&Map<String, Value>]) -> Result<bool, Unclassifiable> {
    let mut marked = false;
    for obj in applicable {
        match obj.get("x-secret") {
            None | Some(Value::Bool(false)) => {}
            Some(Value::Bool(true)) => marked = true,
            Some(_) => return Err(Unclassifiable::MalformedSecretMark),
        }
    }
    Ok(marked)
}

/// Redacts `value` against the union of `schemas` (every schema that applies at its location).
fn redact(
    value: &mut Value,
    schemas: &[&Value],
    types: &BTreeMap<String, Value>,
    depth: usize,
    probes: &mut PatternProbes,
) {
    if schemas.is_empty() {
        return;
    }
    let classified = if depth > MAX_REDACT_DEPTH {
        None
    } else {
        applicable(schemas, types)
            .and_then(|a| marked_secret(&a).map(|m| (a, m)))
            .ok()
    };
    let Some((applicable, marked)) = classified else {
        // Fail closed: a value the walk cannot classify is not published.
        *value = Value::String(REDACTED.into());
        return;
    };
    if marked {
        *value = Value::String(REDACTED.into());
        return;
    }
    match value {
        Value::Object(map) => {
            for (name, member) in map.iter_mut() {
                let mut child: Vec<&Value> = Vec::new();
                let mut unclassifiable = false;
                for obj in &applicable {
                    let mut matched = false;
                    if let Some(prop) = obj.get("properties").and_then(|p| p.get(name)) {
                        matched = true;
                        child.push(prop);
                    }
                    if let Some(Value::Object(patterns)) = obj.get("patternProperties") {
                        for (pattern, pattern_schema) in patterns {
                            match probes.applies(pattern, name) {
                                Some(true) => {
                                    matched = true;
                                    child.push(pattern_schema);
                                }
                                Some(false) => {}
                                // Which entries apply (and so whether the fallbacks do) is unknown.
                                None => unclassifiable = true,
                            }
                        }
                    }
                    // A member this subschema did not evaluate itself falls to its
                    // `additionalProperties`, and (whatever the other subschemas evaluated) to its
                    // `unevaluatedProperties`.
                    if !matched {
                        for key in ["additionalProperties", "unevaluatedProperties"] {
                            if let Some(fallback) = obj.get(key) {
                                child.push(fallback);
                            }
                        }
                    }
                }
                if unclassifiable {
                    // Fail closed: a member whose schemas cannot be collected is not published.
                    *member = Value::String(REDACTED.into());
                } else {
                    redact(member, &child, types, depth + 1, probes);
                }
            }
        }
        Value::Array(items) => {
            for (i, item) in items.iter_mut().enumerate() {
                let mut child: Vec<&Value> = Vec::new();
                for obj in &applicable {
                    if let Some(prefixed) = obj.get("prefixItems").and_then(|p| p.get(i)) {
                        child.push(prefixed);
                    } else if let Some(items_schema) = obj.get("items") {
                        child.push(items_schema);
                    } else if let Some(unevaluated) = obj.get("unevaluatedItems") {
                        child.push(unevaluated);
                    }
                    if let Some(contains) = obj.get("contains") {
                        child.push(contains);
                    }
                }
                redact(item, &child, types, depth + 1, probes);
            }
        }
        _ => {}
    }
}

/// Whether a value is a container with no scalar anywhere inside (`{}`, `[]`, `{ "a": [] }`): nothing
/// in it can be a secret.
fn holds_no_value(value: &Value) -> bool {
    match value {
        Value::Object(map) => map.values().all(holds_no_value),
        Value::Array(items) => items.iter().all(holds_no_value),
        _ => false,
    }
}

fn reserved_params_for(def: &OperationDef) -> Vec<(&'static str, Value)> {
    let mut extra = Vec::new();
    if def.tier >= RiskTier::REVERSIBLE_WRITE {
        extra.push((
            "dryRun",
            json!({
                "type": "boolean",
                "default": false,
                "description": "Plan the call without executing it; the result is a DryRunResult (Spec 02 §8.1).",
                "x-den-template": false
            }),
        ));
    }
    if def.tier == RiskTier::EXTERNAL || DYNAMIC_TIER_OPERATIONS.contains(&def.name.as_str()) {
        extra.push((
            "approvalId",
            json!({
                "$ref": "#/types/ApprovalId",
                "description": "Handle of an in-app approval of this exact call, after APPROVAL_REQUIRED (Spec 02 §8.1, §8.8).",
                "x-den-template": false
            }),
        ));
    }
    extra
}

fn forbid_reserved_result_keys(result: &mut Value) {
    if let Some(obj) = result.as_object_mut() {
        let props = obj.entry("properties").or_insert_with(|| json!({}));
        if let Some(props) = props.as_object_mut() {
            props.insert("dryRun".into(), Value::Bool(false));
            props.insert("draft".into(), Value::Bool(false));
        }
    }
}

/// Builds the `protocol.json` document from a catalog (§9.1), examples redacted for publication (§3).
/// Fails when the catalog does not pass [`lint`]. Consumes the catalog because the shared definitions
/// table is taken out of it.
pub fn build(catalog: Catalog) -> Result<ProtocolDocument, BuildError> {
    let mut doc = build_unredacted(catalog)?;
    doc.redact_examples();
    Ok(doc)
}

/// [`build`] without the redaction step: examples exactly as authored, so `xtask` can validate them
/// against the generated schemas before [`ProtocolDocument::redact_examples`] replaces every secret
/// with `"***"` (a redacted object or number no longer matches its own schema). Never publish this form.
pub fn build_unredacted(mut catalog: Catalog) -> Result<ProtocolDocument, BuildError> {
    let errors = lint(&catalog);
    if !errors.is_empty() {
        return Err(BuildError::Lint(errors));
    }
    // Make sure the result shapes are in the shared table even if no operation references them.
    let dry_run_ref = catalog.ref_for::<crate::results::DryRunResult>();
    let draft_ref = catalog.ref_for::<crate::results::DraftResult>();
    catalog.ref_for::<crate::ids::ApprovalId>();

    let mut ops: Vec<OperationDef> = catalog.operations().values().cloned().collect();
    let mut evs: Vec<EventDef> = catalog.events().values().cloned().collect();
    let payload_tables: BTreeMap<String, BTreeMap<String, u32>> = evs
        .iter()
        .map(|def| {
            let table = catalog
                .payload_versions(&def.r#type)
                .table(def.payload_version)
                .into_iter()
                .map(|(rpc, version)| (rpc.to_string(), version))
                .collect();
            (def.r#type.to_string(), table)
        })
        .collect();
    for def in &mut ops {
        catalog.finish_schema(&mut def.params);
        catalog.finish_schema(&mut def.result);
    }
    for def in &mut evs {
        catalog.finish_schema(&mut def.payload);
    }
    let types: BTreeMap<String, Value> = catalog.take_definitions().into_iter().collect();
    let errors = lint_shared_types(&types);
    if !errors.is_empty() {
        return Err(BuildError::Lint(errors));
    }

    let mut operations = BTreeMap::new();
    for mut def in ops {
        let mut params = def.params.clone().to_value();
        if let Some(obj) = params.as_object_mut() {
            let props = obj.entry("properties").or_insert_with(|| json!({}));
            if let Some(props) = props.as_object_mut() {
                for (name, schema) in reserved_params_for(&def) {
                    props.insert(name.into(), schema);
                }
            }
        }
        let (invocation, authoring) =
            derive_param_schemas(&Schema::try_from(params).expect("object"), &types);
        def.params = invocation;
        let tiered = def.tier >= RiskTier::REVERSIBLE_WRITE;
        if tiered {
            let mut result = def.result.clone().to_value();
            forbid_reserved_result_keys(&mut result);
            def.result = Schema::try_from(result).expect("object");
        }
        let mcp_tool_name = Catalog::is_mcp_exposed(&def).then(|| def.name.mcp_tool_name());
        let name = def.name.to_string();
        let entry = OperationEntry {
            dry_run_result: tiered.then(|| dry_run_ref.clone()),
            draft_result: (def.tier == RiskTier::CONFIG).then(|| draft_ref.clone()),
            mcp_tool_name,
            def,
            params_authoring: authoring,
        };
        operations.insert(name, entry);
    }

    let mut events = BTreeMap::new();
    for def in evs {
        let payload_versions = payload_tables
            .get(def.r#type.as_str())
            .cloned()
            .unwrap_or_default();
        events.insert(
            def.r#type.to_string(),
            EventEntry {
                def,
                payload_versions,
            },
        );
    }

    let mut deprecations = BTreeMap::new();
    for entry in operations.values() {
        if let Some(d) = &entry.def.deprecated {
            deprecations.insert(format!("operation:{}", entry.def.name), d.clone());
        }
    }

    let doc = ProtocolDocument {
        comment: GENERATED_MARKER.into(),
        protocol_version: PROTOCOL_VERSION.into(),
        rpc_version: RPC_VERSION,
        rpc_versions: crate::rpc::RpcVersionRange {
            min: RPC_VERSION_MIN,
            max: RPC_VERSION,
        },
        operations,
        events,
        types,
        errors: ErrorCode::TABLE
            .iter()
            .map(|row| {
                (
                    row.code.to_owned(),
                    ErrorEntry {
                        jsonrpc_code: row.jsonrpc_code,
                        description: row.description.to_owned(),
                    },
                )
            })
            .collect(),
        close_codes: close_code::TABLE
            .iter()
            .map(|row| {
                (
                    row.name.to_owned(),
                    CloseCodeEntry {
                        code: row.code,
                        description: row.description.to_owned(),
                    },
                )
            })
            .collect(),
        protocol_methods: PROTOCOL_METHODS.iter().map(|s| (*s).to_owned()).collect(),
        scopes: KNOWN_SCOPES.iter().map(|s| (*s).to_owned()).collect(),
        reserved_slugs: RESERVED_SLUGS.iter().map(|s| (*s).to_owned()).collect(),
        reserved_run_context_roots: RESERVED_RUN_CONTEXT_ROOTS
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
        dynamic_tier_operations: DYNAMIC_TIER_OPERATIONS
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
        deprecations,
    };
    let errors = doc.lint_typed_examples();
    if !errors.is_empty() {
        return Err(BuildError::Lint(errors));
    }
    Ok(doc)
}

/// The schemas one operation's examples are redacted against.
struct ExampleSchemas<'a> {
    params: &'a Value,
    result: &'a Value,
    dry_run: Option<&'a Value>,
    draft: Option<&'a Value>,
}

/// Redacts one operation example for publication: the authored values are dropped, then the schema
/// walk runs over the published `params` and the result (against the shape it declares). Plan steps of
/// dry-run and draft results name the operation they would call, so their `params` are redacted
/// against that operation's invocation schema; a step naming a target outside this document keeps its
/// `params` only when they hold no value, and is published with them redacted whole otherwise.
fn redact_operation_example(
    example: &mut crate::catalog::OperationExample,
    schemas: &ExampleSchemas<'_>,
    op_params: &BTreeMap<String, Value>,
    types: &BTreeMap<String, Value>,
) {
    example.authored = None;
    redact_secrets(&mut example.params, schemas.params, types);
    let shape_schema = match example.shape {
        ResultShape::Normal => Some(schemas.result),
        ResultShape::DryRun => schemas.dry_run,
        ResultShape::Draft => schemas.draft,
    };
    if let Some(schema) = shape_schema {
        redact_secrets(&mut example.result, schema, types);
    }
    if example.shape != ResultShape::Normal
        && let Some(Value::Array(plan)) = example.result.get_mut("plan")
    {
        for step in plan {
            let schema = step
                .get("operation")
                .and_then(Value::as_str)
                .and_then(|op| op_params.get(op));
            let Some(params) = step.get_mut("params") else {
                continue;
            };
            match schema {
                Some(schema) => redact_secrets(params, schema, types),
                // A target outside this document (a plugin operation) cannot be checked: its params
                // are published only when they hold no value at all (the lint demands that);
                // anything else is redacted whole. Fail closed.
                None if holds_no_value(params) => {}
                None => *params = Value::String(REDACTED.into()),
            }
        }
    }
}

impl ProtocolDocument {
    fn operation_params(&self) -> BTreeMap<String, Value> {
        self.operations
            .iter()
            .map(|(name, entry)| (name.clone(), entry.def.params.as_value().clone()))
            .collect()
    }

    /// The publication boundary of §3. An example built from typed values already holds its published
    /// form (every [`crate::Secret`] serialized as `"***"`); its authored values, kept aside for
    /// validation, are dropped here so the document holds no exposed value at all. On top of that, and
    /// alone for JSON-authored examples, the schema walk replaces every `x-secret` position of every
    /// operation and event example with `"***"`, guided by the published schemas ([`redact_secrets`];
    /// plan steps per [`redact_operation_example`]). Idempotent.
    pub fn redact_examples(&mut self) {
        let types = &self.types;
        let op_params = self.operation_params();
        for entry in self.operations.values_mut() {
            let params = entry.def.params.as_value().clone();
            let result = entry.def.result.as_value().clone();
            let dry_run = entry.dry_run_result.clone();
            let draft = entry.draft_result.clone();
            let schemas = ExampleSchemas {
                params: &params,
                result: &result,
                dry_run: dry_run.as_ref().map(Schema::as_value),
                draft: draft.as_ref().map(Schema::as_value),
            };
            for example in &mut entry.def.examples {
                redact_operation_example(example, &schemas, &op_params, types);
            }
        }
        for entry in self.events.values_mut() {
            entry.def.authored_examples.clear();
            let payload_schema = entry.def.payload.as_value().clone();
            for example in &mut entry.def.examples {
                redact_secrets(example, &payload_schema, types);
            }
        }
    }

    /// The typed-example rule (§3): an example built from typed values publishes nothing the schema
    /// walk would redact, which holds exactly when every secret-bearing position of its Rust types is
    /// a [`crate::Secret`]. A typed example the walk would change holds a secret in its published
    /// form (a plain field with a hand-set `x-secret`, a pre-serialized value passed as "typed", plan
    /// params rendered with secrets exposed), and the value level, not the walk, must be what
    /// withholds it. Checked by [`build_unredacted`] on the final schemas.
    fn lint_typed_examples(&self) -> Vec<LintError> {
        let types = &self.types;
        let op_params = self.operation_params();
        let mut errors = Vec::new();
        for (name, entry) in &self.operations {
            let schemas = ExampleSchemas {
                params: entry.def.params.as_value(),
                result: entry.def.result.as_value(),
                dry_run: entry.dry_run_result.as_ref().map(Schema::as_value),
                draft: entry.draft_result.as_ref().map(Schema::as_value),
            };
            for example in &entry.def.examples {
                if example.authored.is_none() {
                    continue;
                }
                let mut published = example.clone();
                redact_operation_example(&mut published, &schemas, &op_params, types);
                for (what, before, after) in [
                    ("params", &example.params, &published.params),
                    ("result", &example.result, &published.result),
                ] {
                    if before != after {
                        errors.push(LintError {
                            subject: format!("operation:{name}"),
                            message: format!(
                                "typed example {:?}: the published {what} still hold a value at a marked position; that position must be a `Secret<T>` in the Rust type (§3)",
                                example.title
                            ),
                        });
                    }
                }
            }
        }
        for (r#type, entry) in &self.events {
            let payload = entry.def.payload.as_value();
            for (i, example) in entry.def.examples.iter().enumerate() {
                if !entry.def.is_typed_example(i) {
                    continue;
                }
                let mut published = example.clone();
                redact_secrets(&mut published, payload, types);
                if published != *example {
                    errors.push(LintError {
                        subject: format!("event:{type}"),
                        message: format!(
                            "typed example {i}: the published payload still holds a value at a marked position; that position must be a `Secret<T>` in the Rust type (§3)"
                        ),
                    });
                }
            }
        }
        errors
    }

    /// The canonical on-disk form: pretty-printed, sorted maps, `\n` endings, trailing newline (§14).
    pub fn to_json_string(&self) -> String {
        let mut s = serde_json::to_string_pretty(self).expect("protocol document serializes");
        s.push('\n');
        s
    }

    /// A schema that validates an instance against the subschema at `pointer` (a JSON pointer such as
    /// `/operations/plugins.call/result`), resolving `#/types/<Name>` references. This is the
    /// **receiver's** view: the receiving-only fallback branches of `Node` and `Fragment` (§7.2) are in.
    pub fn schema_at(&self, pointer: &str) -> Value {
        let mut root = serde_json::to_value(self).expect("protocol document serializes");
        Self::point(&mut root, pointer);
        root
    }

    /// [`ProtocolDocument::schema_at`] as a **producer** must satisfy it (§7.2, §9.7): every
    /// receiving-only fallback branch (a union branch referencing a type whose `kind` is constrained to
    /// the unknown tags, [`crate::schema::unknown_tag_schema`]) is removed from every published schema
    /// (the shared types, and the operation and event schemas, which inline structured shared types), so
    /// an example or document whose `kind` is not one this build knows fails validation instead of
    /// decoding into the fallback. Examples are validated against this view.
    pub fn producer_schema_at(&self, pointer: &str) -> Value {
        let mut root = self.producer_root();
        Self::point(&mut root, pointer);
        root
    }

    /// The document with every receiving-only fallback branch stripped ([`ProtocolDocument::producer_schema_at`]),
    /// before a pointer is set; [`validate_examples`] builds it once and points it per schema.
    fn producer_root(&self) -> Value {
        let mut root = serde_json::to_value(self).expect("protocol document serializes");
        let fallbacks: Vec<String> = self
            .types
            .iter()
            .filter(|(_, schema)| is_receiving_fallback_type(schema))
            .map(|(name, _)| name.clone())
            .collect();
        if let Some(Value::Object(types)) = root.get_mut("types") {
            for schema in types.values_mut() {
                strip_fallback_branches(schema, &fallbacks);
            }
        }
        if let Some(Value::Object(operations)) = root.get_mut("operations") {
            for entry in operations.values_mut() {
                for key in [
                    "params",
                    "paramsAuthoring",
                    "result",
                    "dryRunResult",
                    "draftResult",
                ] {
                    if let Some(schema) = entry.get_mut(key) {
                        strip_fallback_branches(schema, &fallbacks);
                    }
                }
            }
        }
        if let Some(Value::Object(events)) = root.get_mut("events") {
            for entry in events.values_mut() {
                if let Some(schema) = entry.get_mut("payload") {
                    strip_fallback_branches(schema, &fallbacks);
                }
            }
        }
        root
    }

    fn point(root: &mut Value, pointer: &str) {
        if let Some(obj) = root.as_object_mut() {
            obj.insert("$ref".into(), Value::String(format!("#{pointer}")));
            obj.insert(
                "$schema".into(),
                Value::String("https://json-schema.org/draft/2020-12/schema".into()),
            );
        }
    }
}

/// Whether a shared type is a receiving-only fallback (§7.2): its `kind` property is constrained to any
/// string outside a set of known tags, the shape [`crate::schema::unknown_tag_schema`] produces.
fn is_receiving_fallback_type(schema: &Value) -> bool {
    schema
        .get("properties")
        .and_then(|p| p.get("kind"))
        .and_then(|k| k.get("not"))
        .and_then(|n| n.get("enum"))
        .is_some_and(Value::is_array)
}

/// Whether a union branch is a receiving-only fallback: a `$ref` to one of `fallbacks`, the fallback's
/// shape inlined (operation schemas inline structured shared types, [`derive_param_schemas`]), or either
/// kept whole as an `allOf` member ([`merge_ref_target`]).
fn is_fallback_branch(branch: &Value, fallbacks: &[String]) -> bool {
    let Some(obj) = branch.as_object() else {
        return false;
    };
    if shared_type_name(obj).is_some_and(|name| fallbacks.contains(&name))
        || is_receiving_fallback_type(branch)
    {
        return true;
    }
    obj.get("allOf")
        .and_then(Value::as_array)
        .is_some_and(|members| members.iter().any(|m| is_fallback_branch(m, fallbacks)))
}

/// Removes every receiving-only fallback branch ([`is_fallback_branch`]) from the unions of `schema` and
/// its subschemas.
fn strip_fallback_branches(schema: &mut Value, fallbacks: &[String]) {
    let Some(obj) = schema.as_object_mut() else {
        return;
    };
    for key in ["oneOf", "anyOf"] {
        if let Some(Value::Array(branches)) = obj.get_mut(key) {
            branches.retain(|branch| !is_fallback_branch(branch, fallbacks));
        }
    }
    for (key, member) in obj.iter_mut() {
        // Annotation values (`default`, `examples`, `x-…`) are data, not schemas.
        if is_annotation_key(key) {
            continue;
        }
        match member {
            Value::Object(_) => strip_fallback_branches(member, fallbacks),
            Value::Array(items) => {
                for item in items {
                    strip_fallback_branches(item, fallbacks);
                }
            }
            _ => {}
        }
    }
}

/// A validation failure described without the instance (DEN-53, §3): the values the example validator
/// checks are the authored ones, secrets exposed, and both the validator's `Display` and the `Debug` of
/// its error kind echo the instance (an `anyOf`/`oneOf` kind carries every branch's error with its
/// instance). This names the failing keyword, its location in the schema (which holds no instance data)
/// and the instance path with every member name the schema does not itself spell out replaced by
/// `<key>`: a member reached through `additionalProperties`, `patternProperties` or
/// `unevaluatedProperties` is an authored map key, which can be anything, a secret included.
pub fn describe_validation_error(e: &jsonschema::ValidationError<'_>) -> String {
    format!(
        "`{}` failed at schema location {:?}, instance path {:?}",
        e.kind().keyword(),
        e.schema_path().as_str(),
        safe_instance_path(e.instance_path().as_str(), e.evaluation_path().as_str())
    )
}

/// The instance path with authored map keys masked (see [`describe_validation_error`]). The evaluation
/// path says how each instance segment was reached: `properties/<name>` spells the member out, the
/// array applicators yield indices, and the map applicators yield authored keys. Should the two paths
/// not line up (a keyword that fails without descending, such as `additionalProperties: false`, adds a
/// step the instance path lacks), every segment is masked: a digits-only authored key is still a key.
fn safe_instance_path(instance_path: &str, evaluation_path: &str) -> String {
    let segments: Vec<&str> = instance_path.split('/').skip(1).collect();
    if instance_path.is_empty() {
        return String::new();
    }
    let mut mask = Vec::with_capacity(segments.len());
    let mut tokens = evaluation_path.split('/').skip(1).peekable();
    while let Some(token) = tokens.next() {
        match token {
            "properties" => {
                tokens.next();
                mask.push(false);
            }
            "patternProperties" => {
                tokens.next();
                mask.push(true);
            }
            "additionalProperties" | "unevaluatedProperties" => mask.push(true),
            "items" | "contains" | "unevaluatedItems" => mask.push(false),
            "prefixItems" => {
                tokens.next();
                mask.push(false);
            }
            "allOf" | "anyOf" | "oneOf" | "dependentSchemas" => {
                tokens.next();
            }
            _ => {}
        }
    }
    let aligned = mask.len() == segments.len();
    let mut out = String::new();
    for (i, segment) in segments.iter().enumerate() {
        out.push('/');
        let masked = !aligned || mask[i];
        out.push_str(if masked { "<key>" } else { segment });
    }
    out
}

/// Examples are tests (§8.1, §17.2): every example's params validate against the invocation schema and
/// its result against exactly the shape it declares; every event example validates against its payload
/// schema. The values checked are the authored ones (a typed example keeps them aside with secrets
/// exposed; its published form is already withheld, §3), against the producer's view of the schemas
/// ([`ProtocolDocument::producer_schema_at`]), so an example with an unknown `Node` or `Fragment` kind
/// fails (§7.2, §9.7). Failures are described without the instance ([`describe_validation_error`]).
pub fn validate_examples(doc: &ProtocolDocument) -> Result<(), Vec<String>> {
    let mut failures = Vec::new();
    // One producer view, pointed at each schema in turn: the compiled validator owns what it needs.
    let mut root = doc.producer_root();
    let mut compile = |pointer: &str| {
        ProtocolDocument::point(&mut root, pointer);
        jsonschema::validator_for(&root).map_err(|e| format!("{pointer} does not compile: {e}"))
    };
    for (name, entry) in &doc.operations {
        let params_validator = match compile(&format!("/operations/{name}/params")) {
            Ok(v) => v,
            Err(e) => {
                failures.push(format!("operation {name}: {e}"));
                continue;
            }
        };
        let mut shape_validators: Vec<(ResultShape, jsonschema::Validator)> = Vec::new();
        for (shape, key, present) in [
            (ResultShape::Normal, "result", true),
            (
                ResultShape::DryRun,
                "dryRunResult",
                entry.dry_run_result.is_some(),
            ),
            (
                ResultShape::Draft,
                "draftResult",
                entry.draft_result.is_some(),
            ),
        ] {
            if !present {
                continue;
            }
            match compile(&format!("/operations/{name}/{key}")) {
                Ok(v) => shape_validators.push((shape, v)),
                Err(e) => failures.push(format!("operation {name}: {e}")),
            }
        }
        for example in &entry.def.examples {
            let label = format!("operation {name}, example {:?}", example.title);
            let (params, result) = (example.authored_params(), example.authored_result());
            if let Err(e) = params_validator.validate(params) {
                failures.push(format!(
                    "{label}: params invalid: {}",
                    describe_validation_error(&e)
                ));
            }
            if !shape_validators.iter().any(|(s, _)| *s == example.shape) {
                failures.push(format!(
                    "{label}: declares the {:?} shape, which this operation does not have",
                    example.shape
                ));
            }
            for (shape, validator) in &shape_validators {
                let expected = *shape == example.shape;
                match validator.validate(result) {
                    Err(e) if expected => failures.push(format!(
                        "{label}: result does not match its {shape:?} shape: {}",
                        describe_validation_error(&e)
                    )),
                    Ok(()) if !expected && entry.dry_run_result.is_some() => {
                        failures.push(format!(
                            "{label}: result also matches the {shape:?} shape; shapes must be disjoint"
                        ));
                    }
                    _ => {}
                }
            }
        }
    }
    for (r#type, entry) in &doc.events {
        let validator = match compile(&format!("/events/{type}/payload")) {
            Ok(v) => v,
            Err(e) => {
                failures.push(format!("event {type}: {e}"));
                continue;
            }
        };
        for i in 0..entry.def.examples.len() {
            if let Err(e) = validator.validate(entry.def.authored_example(i)) {
                failures.push(format!(
                    "event {type}, example {i}: {}",
                    describe_validation_error(&e)
                ));
            }
        }
    }
    if failures.is_empty() {
        Ok(())
    } else {
        Err(failures)
    }
}

/// The plugin manifest schema (`schema/plugin.schema.json`, §11): strict, draft 2020-12.
pub fn plugin_manifest_schema() -> Value {
    let mut schema =
        crate::schema::strict_root_schema_for::<crate::manifest::PluginManifest>().to_value();
    if let Some(obj) = schema.as_object_mut() {
        obj.insert(
            "$id".into(),
            Value::String(format!(
                "{}plugin.schema.json",
                crate::version::SCHEMA_URI_BASE
            )),
        );
        obj.insert("$comment".into(), Value::String(GENERATED_MARKER.into()));
    }
    schema
}

/// Pretty JSON with a trailing newline, the canonical form of every generated JSON file (§14).
pub fn to_canonical_json(value: &Value) -> String {
    let mut s = serde_json::to_string_pretty(value).expect("value serializes");
    s.push('\n');
    s
}

