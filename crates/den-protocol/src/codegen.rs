/// A catalog lint finding (§9.7).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LintError {
    /// `operation:<name>`, `event:<type>` or `catalog`.
    pub subject: String,
    /// What is wrong.
    pub message: String,
}

impl fmt::Display for LintError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.subject, self.message)
    }
}

/// Errors of [`build`].
#[derive(Debug)]
pub enum BuildError {
    /// The catalog failed lint; nothing was generated.
    Lint(Vec<LintError>),
}

impl fmt::Display for BuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Lint(errors) => {
                writeln!(f, "catalog lint failed with {} finding(s):", errors.len())?;
                for e in errors {
                    writeln!(f, "  - {e}")?;
                }
                Ok(())
            }
        }
    }
}

impl std::error::Error for BuildError {}

/// MCP tool-name rule (§9.6): `^[a-z0-9_]{1,64}$`.
pub fn is_valid_mcp_tool_name(name: &str) -> bool {
    (1..=64).contains(&name.len())
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}

/// MCP property-name rule (§9.6): `^[A-Za-z0-9_.-]{1,64}$`.
pub fn is_valid_mcp_property_name(name: &str) -> bool {
    (1..=64).contains(&name.len())
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '-')
}

/// Maximum MCP tool description length (§9.6).
pub const MCP_DESCRIPTION_MAX: usize = 4096;

/// Lints the catalog (§9.7). Structural checks only; example validation against the generated schemas
/// happens in `xtask` and in the crate's tests, where a JSON Schema validator is available.
pub fn lint(catalog: &Catalog) -> Vec<LintError> {
    let mut errors = Vec::new();
    for (name, def) in catalog.operations() {
        let subject = format!("operation:{name}");
        let mut err = |message: String| {
            errors.push(LintError {
                subject: subject.clone(),
                message,
            })
        };
        if is_protocol_method(name.as_str()) {
            err("is a protocol method (§12), never a catalog operation".into());
        }
        if def.title.as_str().trim().is_empty() {
            err("missing title".into());
        }
        if def.description.as_str().trim().is_empty() {
            err("missing description".into());
        }
        if def.since.trim().is_empty() {
            err("missing `since`".into());
        }
        lint_object_root(def.params.as_value(), "params", &mut err);
        if let Some(props) = properties_of(def.params.as_value()) {
            for reserved in ["dryRun", "approvalId"] {
                if props.contains_key(reserved) {
                    err(format!(
                        "author params define the reserved param `{reserved}`"
                    ));
                }
            }
            for prop in props.keys() {
                if Catalog::is_mcp_exposed(def) && !is_valid_mcp_property_name(prop) {
                    err(format!(
                        "MCP property name {prop:?} violates ^[A-Za-z0-9_.-]{{1,64}}$"
                    ));
                }
            }
        }
        if def.tier >= RiskTier::REVERSIBLE_WRITE {
            lint_object_root(def.result.as_value(), "result (tier ≥ 1)", &mut err);
        }
        if let Some(props) = properties_of(def.result.as_value()) {
            for reserved in ["dryRun", "draft"] {
                if props.contains_key(reserved) {
                    err(format!(
                        "result schema defines the reserved result key `{reserved}`"
                    ));
                }
            }
        }
        if def.examples.is_empty() {
            err("needs at least one example".into());
        }
        let has = |shape: ResultShape| def.examples.iter().any(|e| e.shape == shape);
        if def.tier >= RiskTier::REVERSIBLE_WRITE && !has(ResultShape::DryRun) {
            err("tier ≥ 1 operations need a dry-run example".into());
        }
        if def.tier == RiskTier::CONFIG && !has(ResultShape::Draft) {
            err("tier-2 configuration operations need a draft example".into());
        }
        if def.tier < RiskTier::REVERSIBLE_WRITE && has(ResultShape::DryRun) {
            err("tier-0 operations have no dry-run result".into());
        }
        if def.tier != RiskTier::CONFIG && has(ResultShape::Draft) {
            err("only tier-2 configuration operations have a draft result".into());
        }
        for example in &def.examples {
            let has_dry_run = example.params.get("dryRun").and_then(Value::as_bool) == Some(true);
            if (example.shape == ResultShape::DryRun) != has_dry_run {
                err(format!(
                    "example {:?}: `dryRun: true` in params must match the dry-run shape",
                    example.title
                ));
            }
        }
        if def.tier == RiskTier::DANGEROUS && def.expose.mcp {
            err("a core tier-4 operation must not be marked `expose.mcp` (D-030)".into());
        }
        if Catalog::is_mcp_exposed(def) {
            let tool = name.mcp_tool_name();
            if !is_valid_mcp_tool_name(&tool) {
                err(format!(
                    "MCP tool name {tool:?} violates ^[a-z0-9_]{{1,64}}$"
                ));
            }
            if def.description.as_str().len() > MCP_DESCRIPTION_MAX {
                err(format!(
                    "MCP description exceeds {MCP_DESCRIPTION_MAX} characters"
                ));
            }
        }
        lint_value_mode_enums(def.params.as_value(), "params", &mut err);
    }
    let mut tool_names: BTreeMap<String, &OperationName> = BTreeMap::new();
    for (name, def) in catalog.operations() {
        if Catalog::is_mcp_exposed(def)
            && let Some(prev) = tool_names.insert(name.mcp_tool_name(), name)
        {
            errors.push(LintError {
                subject: format!("operation:{name}"),
                message: format!("MCP tool name collides with operation {prev}"),
            });
        }
    }
    for (r#type, def) in catalog.events() {
        let subject = format!("event:{type}");
        let mut err = |message: String| {
            errors.push(LintError {
                subject: subject.clone(),
                message,
            })
        };
        if def.title.as_str().trim().is_empty() {
            err("missing title".into());
        }
        if def.description.as_str().trim().is_empty() {
            err("missing description".into());
        }
        if def.payload_version == 0 {
            err("payloadVersion starts at 1".into());
        }
        lint_object_root(def.payload.as_value(), "payload", &mut err);
        if let Some(props) = properties_of(def.payload.as_value()) {
            for prop in props.keys() {
                if is_reserved_run_context_root(prop) {
                    err(format!(
                        "payload declares the reserved run-context root {prop:?}"
                    ));
                }
            }
            for filter in &def.filters {
                let head = filter.field.split('.').next().unwrap_or_default();
                if !props.contains_key(head) {
                    err(format!(
                        "filter field {:?} is not a payload property",
                        filter.field
                    ));
                }
            }
        }
        if def.examples.is_empty() {
            err("needs at least one example payload".into());
        }
    }
    errors
}

fn properties_of(schema: &Value) -> Option<&Map<String, Value>> {
    schema.get("properties").and_then(Value::as_object)
}

fn lint_object_root(schema: &Value, what: &str, err: &mut impl FnMut(String)) {
    let Some(obj) = schema.as_object() else {
        err(format!(
            "{what} root must be a schema object with `type: object`"
        ));
        return;
    };
    if obj.get("type").and_then(Value::as_str) != Some("object") {
        err(format!("{what} root must be `type: object`"));
    }
    for key in ["oneOf", "anyOf", "allOf"] {
        if obj.contains_key(key) {
            err(format!("{what} root must not use `{key}` (§9.6)"));
        }
    }
}

fn lint_value_mode_enums(schema: &Value, path: &str, err: &mut impl FnMut(String)) {
    let Some(obj) = schema.as_object() else {
        return;
    };
    if let Some(Value::Array(members)) = obj.get("enum")
        && members
            .iter()
            .any(|m| m.as_str().is_some_and(|s| s.starts_with('{')))
    {
        err(format!(
            "{path}: enum member starts with `{{`, which a value-mode field treats as a template (§10.1)"
        ));
    }
    if let Some(props) = properties_of(schema) {
        for (name, prop) in props {
            lint_value_mode_enums(prop, &format!("{path}/{name}"), err);
        }
    }
    if let Some(items) = obj.get("items") {
        lint_value_mode_enums(items, &format!("{path}/items"), err);
    }
}

/// Template modes of §10.1.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TemplateMode {
    /// Literal, never parsed.
    Literal,
    /// Mixed text and `{…}` forms; always renders to a string.
    Text,
    /// Exactly one `{…}` form; the rendered JSON value replaces the field.
    Value,
}

impl TemplateMode {
    fn to_json(self) -> Value {
        match self {
            Self::Literal => Value::Bool(false),
            Self::Text => Value::String("text".into()),
            Self::Value => Value::String("value".into()),
        }
    }

    fn from_json(value: &Value) -> Option<Self> {
        match value {
            Value::Bool(false) => Some(Self::Literal),
            Value::String(s) if s == "text" => Some(Self::Text),
            Value::String(s) if s == "value" => Some(Self::Value),
            _ => None,
        }
    }
}

/// Resolves a leaf's template mode (§10.1): an explicit `x-den-template` wins; otherwise numbers,
/// integers, booleans and enum strings are `value`, strings with `x-ui.variables: true` are `text`, and
/// everything else is literal.
pub fn resolve_template_mode(leaf: &Value, types: &BTreeMap<String, Value>) -> TemplateMode {
    let Some(obj) = leaf.as_object() else {
        return TemplateMode::Literal;
    };
    if let Some(explicit) = obj.get("x-den-template").and_then(TemplateMode::from_json) {
        return explicit;
    }
    if let Some(target) = resolve_ref(obj, types) {
        return resolve_template_mode(target, types);
    }
    let ty = obj.get("type").and_then(Value::as_str);
    match ty {
        Some("number" | "integer" | "boolean") => TemplateMode::Value,
        Some("string") if obj.contains_key("enum") || obj.contains_key("const") => {
            TemplateMode::Value
        }
        Some("string") => {
            let variables = obj
                .get("x-ui")
                .and_then(|ui| ui.get("variables"))
                .and_then(Value::as_bool)
                .unwrap_or(false);
            if variables {
                TemplateMode::Text
            } else {
                TemplateMode::Literal
            }
        }
        _ => TemplateMode::Literal,
    }
}

fn resolve_ref<'a>(
    obj: &Map<String, Value>,
    types: &'a BTreeMap<String, Value>,
) -> Option<&'a Value> {
    let r = obj.get("$ref")?.as_str()?;
    let name = r
        .strip_prefix("#/types/")
        .or_else(|| r.strip_prefix("#/$defs/"))?;
    types.get(name)
}

/// Derives the invocation and authoring schemas of an operation from its author params (§10.1).
/// Returns `(params, paramsAuthoring)`: both carry a resolved `x-den-template` on every leaf; in
/// `paramsAuthoring` every value-mode leaf becomes `anyOf: [<concrete>, TemplateString]`.
pub fn derive_param_schemas(params: &Schema, types: &BTreeMap<String, Value>) -> (Schema, Schema) {
    let mut invocation = params.clone().to_value();
    let mut authoring = params.clone().to_value();
    annotate_leaves(&mut invocation, types, false);
    annotate_leaves(&mut authoring, types, true);
    (
        Schema::try_from(invocation).expect("object"),
        Schema::try_from(authoring).expect("object"),
    )
}

fn annotate_leaves(schema: &mut Value, types: &BTreeMap<String, Value>, authoring: bool) {
    let Some(obj) = schema.as_object_mut() else {
        return;
    };
    let is_object =
        obj.get("type").and_then(Value::as_str) == Some("object") || obj.contains_key("properties");
    if is_object {
        obj.entry("x-den-template").or_insert(Value::Bool(false));
        if let Some(Value::Object(props)) = obj.get_mut("properties") {
            for prop in props.values_mut() {
                annotate_leaves(prop, types, authoring);
            }
        }
        if let Some(additional) = obj.get_mut("additionalProperties")
            && additional.is_object()
        {
            annotate_leaves(additional, types, authoring);
        }
        return;
    }
    if obj.get("type").and_then(Value::as_str) == Some("array") {
        let explicit = obj.get("x-den-template").and_then(TemplateMode::from_json);
        obj.insert(
            "x-den-template".into(),
            explicit.unwrap_or(TemplateMode::Literal).to_json(),
        );
        if explicit != Some(TemplateMode::Value)
            && let Some(items) = obj.get_mut("items")
        {
            annotate_leaves(items, types, authoring);
        }
        if explicit == Some(TemplateMode::Value) && authoring {
            widen_to_template(schema);
        }
        return;
    }
    // A `$ref` to a shared object type: authoring needs the leaves, so inline a copy.
    if let Some(target) = resolve_ref(obj, types)
        && target.get("type").and_then(Value::as_str) == Some("object")
    {
        let mut inlined = target.clone();
        if let Some(desc) = obj.get("description").cloned()
            && let Some(inl) = inlined.as_object_mut()
        {
            inl.insert("description".into(), desc);
        }
        annotate_leaves(&mut inlined, types, authoring);
        *schema = inlined;
        return;
    }
    let mode = resolve_template_mode(&Value::Object(obj.clone()), types);
    obj.insert("x-den-template".into(), mode.to_json());
    if authoring && mode == TemplateMode::Value {
        widen_to_template(schema);
    }
}

fn widen_to_template(schema: &mut Value) {
    let Some(obj) = schema.as_object_mut() else {
        return;
    };
    let description = obj.remove("description");
    let mut concrete = std::mem::take(obj);
    concrete.remove("x-den-template");
    let mut widened = Map::new();
    if let Some(desc) = description {
        widened.insert("description".into(), desc);
    }
    widened.insert(
        "anyOf".into(),
        json!([Value::Object(concrete), template_string_schema().to_value()]),
    );
    widened.insert("x-den-template".into(), Value::String("value".into()));
    *obj = widened;
}

fn reserved_params_for(def: &OperationDef) -> Vec<(&'static str, Value)> {
    let mut extra = Vec::new();
    if def.tier >= RiskTier::REVERSIBLE_WRITE {
        extra.push((
            "dryRun",
            json!({
                "type": "boolean",
                "default": false,
                "description": "Plan the call without executing it; the result is a DryRunResult (Spec 02 §8.1).",
                "x-den-template": false
            }),
        ));
    }
    if def.tier == RiskTier::EXTERNAL || DYNAMIC_TIER_OPERATIONS.contains(&def.name.as_str()) {
        extra.push((
            "approvalId",
            json!({
                "$ref": "#/types/ApprovalId",
                "description": "Handle of an in-app approval of this exact call, after APPROVAL_REQUIRED (Spec 02 §8.1, §8.8).",
                "x-den-template": false
            }),
        ));
    }
    extra
}

fn forbid_reserved_result_keys(result: &mut Value) {
    if let Some(obj) = result.as_object_mut() {
        let props = obj.entry("properties").or_insert_with(|| json!({}));
        if let Some(props) = props.as_object_mut() {
            props.insert("dryRun".into(), Value::Bool(false));
            props.insert("draft".into(), Value::Bool(false));
        }
    }
}

/// Builds the `protocol.json` document from a catalog (§9.1). Fails when the catalog does not pass
/// [`lint`]. Consumes the catalog because the shared definitions table is taken out of it.
pub fn build(mut catalog: Catalog) -> Result<ProtocolDocument, BuildError> {
    let errors = lint(&catalog);
    if !errors.is_empty() {
        return Err(BuildError::Lint(errors));
    }
    // Make sure the result shapes are in the shared table even if no operation references them.
    let dry_run_ref = catalog.ref_for::<crate::results::DryRunResult>();
    let draft_ref = catalog.ref_for::<crate::results::DraftResult>();
    catalog.ref_for::<crate::ids::ApprovalId>();

    let mut ops: Vec<OperationDef> = catalog.operations().values().cloned().collect();
    let mut evs: Vec<EventDef> = catalog.events().values().cloned().collect();
    for def in &mut ops {
        catalog.finish_schema(&mut def.params);
        catalog.finish_schema(&mut def.result);
    }
    for def in &mut evs {
        catalog.finish_schema(&mut def.payload);
    }
    let types: BTreeMap<String, Value> = catalog.take_definitions().into_iter().collect();

    let mut operations = BTreeMap::new();
    for mut def in ops {
        let mut params = def.params.clone().to_value();
        if let Some(obj) = params.as_object_mut() {
            let props = obj.entry("properties").or_insert_with(|| json!({}));
            if let Some(props) = props.as_object_mut() {
                for (name, schema) in reserved_params_for(&def) {
                    props.insert(name.into(), schema);
                }
            }
        }
        let (invocation, authoring) =
            derive_param_schemas(&Schema::try_from(params).expect("object"), &types);
        def.params = invocation;
        let tiered = def.tier >= RiskTier::REVERSIBLE_WRITE;
        if tiered {
            let mut result = def.result.clone().to_value();
            forbid_reserved_result_keys(&mut result);
            def.result = Schema::try_from(result).expect("object");
        }
        let mcp_tool_name = Catalog::is_mcp_exposed(&def).then(|| def.name.mcp_tool_name());
        let name = def.name.to_string();
        let entry = OperationEntry {
            dry_run_result: tiered.then(|| dry_run_ref.clone()),
            draft_result: (def.tier == RiskTier::CONFIG).then(|| draft_ref.clone()),
            mcp_tool_name,
            def,
            params_authoring: authoring,
        };
        operations.insert(name, entry);
    }

    let mut events = BTreeMap::new();
    for def in evs {
        let mut payload_versions = BTreeMap::new();
        for rpc in RPC_VERSION_MIN..=RPC_VERSION {
            payload_versions.insert(rpc.to_string(), def.payload_version);
        }
        events.insert(
            def.r#type.to_string(),
            EventEntry {
                def,
                payload_versions,
            },
        );
    }

    let mut deprecations = BTreeMap::new();
    for entry in operations.values() {
        if let Some(d) = &entry.def.deprecated {
            deprecations.insert(format!("operation:{}", entry.def.name), d.clone());
        }
    }

    Ok(ProtocolDocument {
        comment: GENERATED_MARKER.into(),
        protocol_version: PROTOCOL_VERSION.into(),
        rpc_version: RPC_VERSION,
        rpc_versions: crate::rpc::RpcVersionRange {
            min: RPC_VERSION_MIN,
            max: RPC_VERSION,
        },
        operations,
        events,
        types,
        errors: ErrorCode::TABLE
            .iter()
            .map(|row| {
                (
                    row.code.to_owned(),
                    ErrorEntry {
                        jsonrpc_code: row.jsonrpc_code,
                        description: row.description.to_owned(),
                    },
                )
            })
            .collect(),
        close_codes: close_code::TABLE
            .iter()
            .map(|row| {
                (
                    row.name.to_owned(),
                    CloseCodeEntry {
                        code: row.code,
                        description: row.description.to_owned(),
                    },
                )
            })
            .collect(),
        protocol_methods: PROTOCOL_METHODS.iter().map(|s| (*s).to_owned()).collect(),
        reserved_slugs: RESERVED_SLUGS.iter().map(|s| (*s).to_owned()).collect(),
        reserved_run_context_roots: RESERVED_RUN_CONTEXT_ROOTS
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
        deprecations,
    })
}

impl ProtocolDocument {
    /// The canonical on-disk form: pretty-printed, sorted maps, `\n` endings, trailing newline (§14).
    pub fn to_json_string(&self) -> String {
        let mut s = serde_json::to_string_pretty(self).expect("protocol document serializes");
        s.push('\n');
        s
    }

    /// A schema that validates an instance against the subschema at `pointer` (a JSON pointer such as
    /// `/operations/plugins.call/result`), resolving `#/types/<Name>` references.
    pub fn schema_at(&self, pointer: &str) -> Value {
        let mut root = serde_json::to_value(self).expect("protocol document serializes");
        if let Some(obj) = root.as_object_mut() {
            obj.insert("$ref".into(), Value::String(format!("#{pointer}")));
            obj.insert(
                "$schema".into(),
                Value::String("https://json-schema.org/draft/2020-12/schema".into()),
            );
        }
        root
    }
}

/// The plugin manifest schema (`schema/plugin.schema.json`, §11): strict, draft 2020-12.
pub fn plugin_manifest_schema() -> Value {
    let mut schema =
        crate::schema::strict_root_schema_for::<crate::manifest::PluginManifest>().to_value();
    if let Some(obj) = schema.as_object_mut() {
        obj.insert(
            "$id".into(),
            Value::String(format!(
                "{}plugin.schema.json",
                crate::version::SCHEMA_URI_BASE
            )),
        );
        obj.insert("$comment".into(), Value::String(GENERATED_MARKER.into()));
    }
    schema
}

/// Pretty JSON with a trailing newline, the canonical form of every generated JSON file (§14).
pub fn to_canonical_json(value: &Value) -> String {
    let mut s = serde_json::to_string_pretty(value).expect("value serializes");
    s.push('\n');
    s
}

