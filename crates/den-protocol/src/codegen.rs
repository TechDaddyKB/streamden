/// The canonical artifact (§9.1): the catalog, shared types, errors and reserved names of one build.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema, TS)]
#[serde(rename_all = "camelCase")]
pub struct ProtocolDocument {
    /// The generated-file marker.
    #[serde(rename = "$comment")]
    #[ts(rename = "$comment")]
    pub comment: String,
    /// SemVer protocol version (§7.1).
    pub protocol_version: String,
    /// The current `rpcVersion` (§7.1).
    pub rpc_version: u32,
    /// The `rpcVersion` range this build serves.
    pub rpc_versions: crate::rpc::RpcVersionRange,
    /// Operations by name, with their generated schemas (§8.1, §10.1).
    pub operations: BTreeMap<String, OperationEntry>,
    /// Event types by type, with one payload schema per version (§5.2).
    pub events: BTreeMap<String, EventEntry>,
    /// Shared types, the target of every `#/types/<Name>` reference.
    #[ts(as = "BTreeMap<String, serde_json::Value>")]
    pub types: BTreeMap<String, Value>,
    /// The application error table (§8.5).
    pub errors: BTreeMap<String, ErrorEntry>,
    /// WebSocket close codes by name (§8.3).
    pub close_codes: BTreeMap<String, CloseCodeEntry>,
    /// Protocol methods and notifications (§12); never catalog operations.
    pub protocol_methods: Vec<String>,
    /// Scope patterns (§8.7); `<…>` marks an optional qualifier.
    pub scopes: Vec<String>,
    /// Slugs reserved for core (§4).
    pub reserved_slugs: Vec<String>,
    /// Reserved run-context roots (§6.3).
    pub reserved_run_context_roots: Vec<String>,
    /// Deprecated items (§7.4), as `<kind>:<name>` keys.
    pub deprecations: BTreeMap<String, crate::catalog::Deprecation>,
}

