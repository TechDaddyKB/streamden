//! Placeholder generator: writes TypeScript bindings from `b4-core`.
//! CI reruns it and fails on `git diff --exit-code` if the committed output is stale.

use std::fmt::Write as _;
use std::path::Path;

fn render() -> String {
    let mut out = String::from("// @generated by crates/b4-codegen. Do not edit.\n\n");
    out.push_str("export const EVENT_KINDS = [\n");
    for kind in b4_core::EVENT_KINDS {
        writeln!(out, "  \"{kind}\",").expect("writing to a String cannot fail");
    }
    out.push_str("] as const;\n\nexport type EventKind = (typeof EVENT_KINDS)[number];\n");
    out
}

fn main() -> std::io::Result<()> {
    let target = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/b4-web/src/generated/event-kind.ts");
    std::fs::write(target, render())
}
